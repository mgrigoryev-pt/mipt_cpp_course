// Сравните с `Event` в `event.h`: там не написана ни одна, и это правильно —
// все поля умеют копироваться, перемещаться и освобождаться сами, а
// компилятор сгенерирует пять функций лучше, чем их напишут руками: он
// не забудет поле, добавленное завтра, и поставит `noexcept` там, где оно
// верно. По тому же признаку не написана ни одна и здесь: полей три, и все
// три обычные.
//
// Причина ровно одна, и она не про владение ресурсом: копии надо посчитать.
// Счётчика «копий вообще» не существует, перехватить конструкторы
// `std::string` нельзя — это чужой тип. Единственный способ узнать,
// копируется запись или перемещается, — написать конструкторы самому
// и поставить в них по инкременту.
//
// Отсюда неприятное следствие, и его стоит назвать вслух: измеряя, мы меняем
// измеряемое. Написанные руками пять функций компилятор уже не считает
// тривиальными, и вектор таких записей потерял бы право переносить массив
// одним `memcpy` при росте. Здесь это не важно — записи лежат в кольцевом
// буфере, а он не растёт вообще, — в другом месте было бы важно. Хороший
// замер тот, про чьё влияние вы можете сказать, велико оно или нет, а не тот,
// у которого влияния нет.
//
// Про `noexcept` у перемещения: он здесь не обычай, а обещание, на которое
// смотрят контейнеры. Контейнер, которому нужна гарантия «перенос не бросит»,
// без него выберет копирование — то самое, которое вы убираете. Здесь
// контейнер `std::array` внутри вашего буфера, ему всё равно; в векторе
// разница была бы в разы.

#ifndef NANO_EDR_WINDOW_ENTRY_H
#define NANO_EDR_WINDOW_ENTRY_H

#include <string>

#include "copy_stats.h"
#include "event.h"

namespace nano_edr {

// Что окно хранит и почему не событие целиком. Кольцевой буфер лежит
// в объекте, `std::array` внутри требует, чтобы `T` создавался по умолчанию,
// а у `Event` конструктора по умолчанию нет и быть не должно: у него
// инвариант с занятия 2.1, и «пустое событие» ему противоречит. Разрешается
// это не отменой инварианта, а тем, что в окно кладётся ровно то, что нужно
// для печати контекста.
struct WindowEntry {
    Timestamp ts;
    std::string type;
    std::string pid;

    WindowEntry() = default;
    ~WindowEntry() = default;

    WindowEntry(const WindowEntry& other);
    WindowEntry& operator=(const WindowEntry& other);

    WindowEntry(WindowEntry&& other) noexcept;
    WindowEntry& operator=(WindowEntry&& other) noexcept;
};

}  // namespace nano_edr

#endif  // NANO_EDR_WINDOW_ENTRY_H
