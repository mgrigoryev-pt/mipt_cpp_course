// Разбор строки журнала в Event.
//
// Формат один и тот же для журнала событий и для конфигурации сценария:
// пары `ключ=значение`, разделённые пробелами; значение с пробелами берётся
// в двойные кавычки. Экранирования внутри кавычек нет — и это не упущение,
// а решение: в путях Windows обратный слеш встречается на каждом шагу, и
// трактовать его как escape означало бы ломать каждый второй путь.
//
//   ts=1730000001000 type=file_write pid=1042 path="C:\a b.js" size=812
//
// Разбор идёт прямым проходом по символам. Ни регулярных выражений, ни готового
// парсера: строка простая, а проход по символам — то, что нужно уметь.
//
// Почему вход здесь по указателю, когда лекция 3 уже прочитана и ссылки есть.
//
// Эти подписи писались до лекции 3 — на занятии 1.2, когда ссылок не было, —
// и менять их сейчас значило бы сломать выданные тесты занятия 1.2. А они
// проверяют поведение парсера, которое на 1.3 не изменилось: изменился код
// вокруг, а не разбор строки. Терять юнит-покрытие ради косметики подписи —
// плохой обмен.
//
// Заодно получается то, чего на слайде не покажешь: в одном цикле рядом стоят
// обе формы. CheckRules и функции из fields.h берут const-ссылку — они
// написаны после лекции 3; ParseEventLine и ListPushBack берут указатель —
// они старше. Ровно так это и выглядит в живом коде, и вопрос «менять ли
// теперь» — настоящий, а не учебный. Ответ на него зависит от цены поломки
// вызывающих, и на занятии 2.1 эта цена станет нулевой: там Event
// превращается в класс, и переписывается всё равно всё.
//
// Отказы. На этом занятии их два, и оба возвращаются значением, потому что
// битая строка в журнале — не исключительная ситуация, а обычное дело:
// телеметрию пишет чужой код, и одна испорченная строка не повод останавливать
// агента. Разделение отказов по каналам — тема занятия 1.3.

#ifndef NANO_EDR_KIT_PARSE_H
#define NANO_EDR_KIT_PARSE_H

#include <string>
#include <vector>

#include "event.h"

namespace nano_edr {

// Разбирает пары `ключ=значение` из текста.
//
// true — разобрано, пары дописаны в *out. false — строка испорчена (незакрытая
// кавычка, пустой ключ, пара без '='), и тогда *out трогать не следует: часть
// пар в нём уже может лежать, и достраивать событие по обрывку нельзя.
//
// Пустой текст — это успех и ноль пар, а не отказ.
bool ParseFields(const std::string* text, std::vector<Field>* out);

// Разбирает строку журнала целиком: выделяет ts, type и pid в шапку,
// остальное складывает в fields.
//
// Строка без ts или без type считается испорченной: событие без времени
// и без типа бесполезно, а угадывать их нечем. Строка без pid допустима —
// не у всякого события есть процесс.
//
// Пустая строка и строка-комментарий (начинается с '#' или ';') — не событие
// и не ошибка. Для них возвращается false, а *out остаётся пустым; отличить
// их от испорченной строки можно по IsBlankOrComment.
bool ParseEventLine(const std::string* line, Event* out);

// Строку можно пропустить молча: она пустая, состоит из пробелов либо
// начинается с символа комментария.
bool IsBlankOrComment(const std::string* line);

}  // namespace nano_edr

#endif  // NANO_EDR_KIT_PARSE_H
