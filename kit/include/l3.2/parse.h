// Разбор строки журнала. Занятие 2.1.
//
// Формат не изменился: пары `ключ=значение`, разделённые пробелами, значение
// с пробелами в двойных кавычках, экранирования нет.
//
//   ts=1730000001000 type=file_write pid=1042 path="C:\a b.js" size=812
//
// Изменились две вещи, и обе — следствие того, что Event стал классом.
//
// Первое: разбор больше не возвращает Event. У Event есть инвариант, а разбор
// законно не удаётся — журнал пишет чужой код. Собрать объект с инвариантом
// из обрывка нельзя, поэтому разбор отдаёт EventParts, а Event строится
// из них уже целиком, и его конструктор проверяет то, что обещает.
//
// Второе: вход теперь по const-ссылке. На занятиях 1.2 и 1.3 здесь стоял
// указатель — ссылок ещё не было, а потом менять подпись было слишком дорого:
// сломались бы выданные тесты. Сейчас переписывается всё равно всё, и цена
// стала нулевой. Это и есть ответ на вопрос «когда менять подпись»: не когда
// хочется, а когда за это никто не платит.

#ifndef NANO_EDR_KIT_PARSE_H
#define NANO_EDR_KIT_PARSE_H

#include <string>
#include <vector>

#include "event.h"

namespace nano_edr {

// Разбирает пары `ключ=значение` из текста.
//
// true — разобрано, пары дописаны в *out. false — текст испорчен (незакрытая
// кавычка, пустой ключ, слово без '='), и тогда *out использовать нельзя:
// часть пар в нём уже может лежать.
//
// Пустой текст — успех и ноль пар, а не отказ.
bool ParseFields(const std::string& text, std::vector<Field>* out);

// Разбирает строку журнала в части события: ts, type и pid в шапку, остальное
// в fields.
//
// false, если строка испорчена, либо это комментарий или пустая строка, либо
// в ней нет ts или type. Отличить пропускаемую строку от испорченной можно
// через IsBlankOrComment — и нужно: считать их одним счётчиком значит прятать
// проблему журнала за комментарием.
//
// Обратите внимание: здесь только «есть ли ts», без проверки, что это число.
// Число проверяет конструктор Event, потому что это его инвариант, а не дело
// разбора. Один и тот же вопрос не должен проверяться в двух местах: рано или
// поздно проверки разойдутся.
bool ParseEventParts(const std::string& line, EventParts* out);

// Строку можно пропустить молча: пустая, из пробелов, либо начинается
// с символа комментария (# или ;).
bool IsBlankOrComment(const std::string& line);

}  // namespace nano_edr

#endif  // NANO_EDR_KIT_PARSE_H
