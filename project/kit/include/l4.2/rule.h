//
// Что добавилось на 3.2. Во-первых, LambdaRule — правило из произвольного
// предиката; появление лямбд означает, что не под каждое правило нужен класс.
// Это единственное правило, которое комплект объявляет сам: у него нет
// устройства, которое стоило бы выбирать, — только предикат. Во-вторых,
// ваш SequenceRule учится связке `child_of_prev`, и живёт она не на окне
// событий, а на модели сущностей.
//
// Здесь только контракт. Общую часть правил и всех её наследников пишете вы,
// каждого в своём заголовке в `src/`; что должен уметь каждый, сказано ниже,
// на его месте.
//
// Контракт и общая часть — разные вещи, и вопрос «зачем оба» один из главных
// на К2. IRule говорит, что правило **умеет**: только чистые виртуальные
// функции, ни одного поля, и движок больше ничего о правилах не знает. Ваша
// база говорит, что у правил **одинаково**: идентификатор, важность, счётчик,
// список действий. Это переиспользование, а не контракт.
//
// Разделять их стоит потому, что они меняются по разным причинам. Появится
// правило, которому не нужен счётчик, — оно унаследует IRule напрямую.
// Понадобится общим правилам ещё одно поле — оно добавится в вашу базу,
// и движок этого не заметит.
//
// Вектор правил теперь `std::vector<std::unique_ptr<IRule>>`, и это прямой
// ответ на вопрос занятия 2.2. Тогда правила хранились вектором конкретного
// типа, потому что вектор базового класса срезал бы наследника до базовой
// части. Указатель срезать нечего: он одного размера всегда.

