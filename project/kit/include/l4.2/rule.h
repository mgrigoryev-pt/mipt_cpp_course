namespace nano_edr {

// Контракт правила.
class IRule {
 public:
    // Виртуальный деструктор. Без него `delete` по указателю на IRule
    // не вызовет деструктор наследника: условия внутри MatchRule утекут,
    // и утечка будет тем более неприятной, что код при этом выглядит
    // безупречно. Уберите virtual и прогоните под санитайзером —
    // это домашнее задание занятия, и делать его стоит.
    virtual ~IRule() = default;

    virtual const std::string& id() const = 0;
    virtual Severity severity() const = 0;

    // Состояние допустимо: SequenceRule помнит незавершённые совпадения.
    // Отсюда неконстантный метод — и это честнее, чем mutable-поля
    // под словом const.
    virtual bool Check(const Event& event) = 0;

    // ЗАНЯТИЕ 4.1. Тик: событий сейчас нет, есть время убрать за собой.
    //
    // Правило с состоянием — это контейнер, который живёт столько же, сколько
    // процесс, и наполняется из потока. По правилу лекции 13 удаление старого
    // обязано быть частью его дизайна. У SequenceRule незавершённые
    // совпадения снимаются и в Check, но только когда правило вообще
    // проверяется; у ThresholdRule счётчики по ключам не снимаются нигде,
    // и на нагрузочном журнале их набирается по одному на каждый номер
    // процесса, который когда-либо встретился.
    //
    // НЕ чистая виртуальная, и это осознанно: правилу без состояния убирать
    // нечего, и заставлять его писать пустое тело значило бы платить за чужую
    // проблему. Первый метод в этом интерфейсе с телом — и первый случай,
    // когда «интерфейс = только чистые виртуальные» стоит нарушить.
    virtual void OnTick(Timestamp /*now*/) {}

    virtual std::size_t hits() const = 0;
    virtual const std::vector<std::string>& actions() const = 0;
};

// RuleBase ПИШЕТЕ ВЫ — `src/rule_base.h`, занятие 2.2.
//
// Общая часть всякого правила: идентификатор, важность, список действий
// и счётчик срабатываний. Это переиспользование, а не контракт, — контракт
// выше, в IRule.
//
// Что должно быть снаружи, называет выданный `rule_tests.cpp`. Из него
// не видно двух вещей, и обе — ваш выбор: как наследник сообщает базе,
// что правило сработало, и что при этом остаётся приватным.

// MatchRule ПИШЕТЕ ВЫ — `src/match_rule.h`, занятие 2.2.
//
// Все условия выполнены на одном событии. Пустой набор условий срабатывает
// на всём, и защищать это не нужно: правило без условий — ошибка автора
// правила, а не случай, который надо обрабатывать.
//
// Проверка неконстантна: она считает срабатывание. Константный метод
// с mutable-счётчиком прячет изменение состояния за словом const, и это хуже.

// SequenceRule ПИШЕТЕ ВЫ — `src/sequence_rule.h`, занятие 2.3.
//
// Два шага подряд в пределах окна. Первое правило с состоянием: между шагами
// что-то приходится помнить, и это «что-то» — ваш выбор.
//
// Интерфейс задан выданным `engine_tests.cpp`. Чего в нём не видно:
// незавершённые совпадения обязаны выбрасываться по истечении окна, а не
// копиться. Правило с состоянием живёт в долгоживущем агенте, и память,
// растущая с числом событий, — это утечка, просто отложенная.
//
// На 3.2 добавляется связка `child_of_prev`: второй шаг произошёл в процессе,
// чей родитель — процесс первого шага. Окно событий этого не умеет и уметь
// не может — «кто родитель pid» вопрос к модели сущностей, а не к последним
// 256 событиям. Включённая связка отменяет same_pid: требовать одновременно
// «тот же процесс» и «его потомок» бессмысленно. Без модели связка
// не выполняется никогда — правило, которое не может проверить свою связь
// и срабатывает всё равно, хуже молчащего.
//
// На 4.1 добавляется снятие просроченных совпадений вне проверки события:
// правило, которое набрало сотню первых шагов и перестало проверяться,
// держит их до конца прогона.

// ThresholdRule<N> ПИШЕТЕ ВЫ — `src/threshold_rule.h`, занятие 3.1.
//
// Порог: N совпадений за T миллисекунд. «Сорок файлов за шесть секунд»
// нельзя выразить ни одним событием, ни парой: нужен счёт.
//
// N — non-type параметр (лекция 8): сколько отметок помнить. Оно же и предел
// порога — правило с count больше N не сработает никогда, и static_assert
// об этом не скажет, потому что count задаётся во время работы.
//
// Интерфейс задан выданным `template_tests.cpp`. Чего в нём не видно: счёт
// идёт по ключу, обычно "pid", иначе десять безобидных процессов сложатся
// в один детект, а пустой ключ означает «считать всё вместе». Отметки
// времени просятся в ваш кольцевой буфер с занятия 3.1 — но чем хранить,
// решаете вы.
//
// На 4.1 линейный поиск по ключам уступает словарю, цикл со счётчиком —
// алгоритму, и появляется вытеснение счётчиков, к которым давно
// не обращались. Делается это по замеру, и замер — часть занятия.

}  // namespace nano_edr

#endif  // NANO_EDR_KIT_RULE_H
