// Правила из файла. Занятие 4.2.
//
// Пять занятий правила жили в коде, и это было правильно: пока их шесть штук
// и они меняются вместе с движком, файл конфигурации — лишний слой между
// вами и задачей. Теперь их десять, они устоялись, и цена перекомпиляции
// ради одной подстроки стала заметной. Вот тогда и заводят конфигурацию.
//
// ЧТО ЭТО МЕНЯЕТ, КРОМЕ УДОБСТВА
//
// Правило в коде проверял компилятор. Опечатка в имени условия была ошибкой
// сборки, несуществующее поле — ошибкой сборки, перепутанный тип аргумента —
// ошибкой сборки. Правило в файле не проверяет никто, кроме этого загрузчика.
//
// Всё, что раньше ловилось на этапе компиляции, стало вашей работой во время
// выполнения. Отсюда два следствия, и оба обязательные:
//
//   1. загрузчик придирчив. Неизвестный ключ — отказ, а не «пропустим».
//      Тихо проигнорированная строка конфигурации — это правило, которое
//      человек написал, а агент не применил, и узнает об этом человек
//      после инцидента;
//   2. отказ называет номер строки. Конфигурация без номера строки
//      в диагностике — это конфигурация, которую отлаживают перебором.
//
// ПОЧЕМУ expected, А НЕ ИСКЛЮЧЕНИЕ
//
// Битый файл конфигурации — ожидаемый исход, а не нарушение контракта: файл
// пишет человек, и он ошибается. Вызывающий обязан на это отреагировать —
// напечатать причину и не запускаться, — и expected заставляет его хотя бы
// посмотреть на результат.
//
// Сравните с Event: там конструктор бросает, потому что нарушение инварианта
// означает, что дальше работать нечем и вызывающему нечего решать. Здесь
// решать есть что: можно отказаться стартовать, можно взять встроенный набор,
// можно попросить другой файл. Разные вопросы — разные каналы.
//
// ЧЕГО ЗДЕСЬ НЕТ И НЕ БУДЕТ
//
// Правила с произвольным предикатом на C++ (LambdaRule) через файл
// не выражаются, и попытка их выразить превратила бы конфигурацию в язык
// программирования. Такие правила остаются в коде, и это нормальное
// устройство: конфигурация покрывает то, что меняется часто, код — то,
// что меняется редко и требует выражения.
//
// В наборе агента таких правил одно из десяти.
//
// ЧТО ПЕРЕЕЗЖАЕТ В ФАЙЛ НА ЭТОМ ЗАНЯТИИ
//
// Только правила вида match — их в наборе шесть. Два последовательностных
// и одно пороговое остаются в коде, как и правило с предикатом: разбор
// их ключей ничего не добавляет к теме занятия, а объём загрузчика поднимает
// заметно. Довести формат до всех трёх видов — продвинутая часть занятия.
//
// Смешанный набор — половина правил из файла, половина из кода — это
// не переходное состояние, а штатное устройство: движку всё равно, откуда
// приехало правило, потому что он видит IRule.

#ifndef NANO_EDR_KIT_RULE_LOADER_H
#define NANO_EDR_KIT_RULE_LOADER_H

#include <cstddef>
#include <cstdint>
#include <expected>
#include <memory>
#include <string>
#include <string_view>
#include <vector>

#include "rule.h"

namespace nano_edr {

// Движок пишет студент (`src/rule_engine.h`, занятие 2.3), и здесь он нужен
// только указателем в MoveInto — значит хватает предобъявления, а полный
// тип подключает тот, кто MoveInto зовёт.
class RuleEngine;

class EntityModel;

// Отказ разбора конфигурации.
//
// line нумеруется с единицы, как её видит человек в редакторе. Ноль означает
// «к строке не привязано»: файл не открылся, файл пуст, правило без условий
// (о нём говорит строка его заголовка, но иногда и её нет).
struct ConfigError {
    std::string path;
    std::size_t line = 0;
    std::string message;

    // «rules.conf:14: неизвестный оператор startswith». Формат один на все
    // отказы: именно так его читают инструменты, привыкшие к выводу
    // компилятора.
    std::string Message() const;
};

// Набор правил, загруженный из файла.
//
// Владеет правилами до тех пор, пока их не заберёт движок. Копирование
// запрещено само собой: внутри unique_ptr, и это ровно то, что нужно —
// два набора над одними правилами были бы двойным владением.
class RuleSet {
 public:
    void Add(std::unique_ptr<IRule> rule);

    std::size_t size() const { return rules_.size(); }
    bool empty() const { return rules_.empty(); }

    // Отдать правила движку. После вызова набор пуст: владение переехало,
    // и держать его здесь означало бы делать вид, что оно ещё тут.
    void MoveInto(RuleEngine* engine);

 private:
    std::vector<std::unique_ptr<IRule>> rules_;
};

// Настройки загрузки — то, чего нет в файле, но без чего правила не собрать.
//
// Оба поля нужны только видам правил из продвинутой части. В базовой части
// структура передаётся пустой, и это не заготовка на будущее: подпись Load
// не должна меняться от того, сколько видов правил вы успели поддержать.
struct LoadOptions {
    // Модель сущностей для связок, которые спрашивают о родстве процессов.
    // nullptr допустим: правило со связкой child_of_prev тогда молчит, как
    // и заведённое из кода.
    const EntityModel* model = nullptr;

    // Сколько модельного времени пороговое правило держит счётчик по ключу
    // без обращений. Приходит от сервера, а не из файла правил: это настройка
    // расхода памяти на конкретном хосте, а не свойство правила.
    // Ключ idle_ms в самом правиле её перекрывает.
    uint64_t bucket_idle_ms = 0;
};

// Загрузка правил из файла.
//
// Формат — секции `[rule <id>]`, внутри пары `ключ = значение`. Повторяющийся
// ключ означает «ещё одно», а не «вместо»: три строки match — это три условия,
// объединённые И.
//
//   [rule script_host_from_temp]
//   kind     = match
//   severity = high
//   match    = type is process_start
//   match    = image ends_with wscript.exe or image ends_with cscript.exe
//   match    = cmdline contains "\Temp\"
//   action   = kill_process
//
// Условие — «поле оператор значение»; альтернативы внутри одной строки
// разделяются словом `or` и означают ИЛИ. Операторы: is (только для поля
// type), equals, contains, ends_with. Значение с пробелами — в кавычках.
//
// Ключи вида match: kind, severity, match, action. Больше в базовой части
// не нужно ничего, и всё остальное загрузчик обязан отвергнуть — неизвестный
// ключ это опечатка, а опечатка в конфигурации детектов есть правило,
// которого нет.
//
// Продвинутая часть добавляет ещё два вида: sequence (first, second,
// window_ms, link) и threshold (match, count, window_ms, key, idle_ms).
// Описание их ключей — в rules.conf.
class RuleLoader {
 public:
    // Отказ ожидаем и обязан быть замечен, поэтому expected.
    [[nodiscard]] static std::expected<RuleSet, ConfigError> Load(
        const std::string& path, const LoadOptions& options);

    // Разбор из текста — для тестов и для конфигурации, пришедшей от сервера
    // строкой, а не файлом. path попадает только в диагностику.
    [[nodiscard]] static std::expected<RuleSet, ConfigError> Parse(
        std::string_view text, const std::string& path,
        const LoadOptions& options);
};

}  // namespace nano_edr

#endif  // NANO_EDR_KIT_RULE_LOADER_H
