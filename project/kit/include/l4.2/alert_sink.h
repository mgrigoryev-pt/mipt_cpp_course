// Получатели детектов. Занятие 3.2.
//
// Критерий занятия дословно: движок не знает ни про консоль, ни про файлы,
// ни про edr.h — только про sink. Здесь и определено, что такое sink.
//
// ПОЧЕМУ НЕ ИНТЕРФЕЙС
//
// Занятие 2.3 научило другому приёму: `ISink` с чистой виртуальной функцией,
// наследники, вектор `unique_ptr<ISink>`. Он работает и здесь, и был бы
// не хуже — но у него есть цена, которая на четвёртом получателе становится
// заметной: чтобы стать получателем, тип обязан наследовать ваш интерфейс.
//
// Лямбда наследовать не может. А получатель-счётчик в тесте — это ровно
// лямбда: две строки, живёт три строки, объявлять под неё класс глупо.
//
// `AlertSink = Function<void(const Detection&)>` снимает требование
// наследования: получателем становится всё, что вызывается с Detection.
// Классы ниже — получатели с состоянием, которым класс всё равно нужен;
// в тесте рядом с ними живёт лямбда, и движок не отличает одно от другого.
//
// ЗНАЧЕНИЕ, А НЕ УКАЗАТЕЛЬ
//
// Sink передаётся по значению и хранится по значению. Отсюда следует
// то, что и делает этот приём полезным: получателей можно собирать
// из получателей. FanOutSink — получатель, раздающий нескольким; DedupSink —
// получатель, стоящий перед другим получателем. Ни движку, ни самим
// получателям про это знать не нужно.

#ifndef NANO_EDR_KIT_ALERT_SINK_H
#define NANO_EDR_KIT_ALERT_SINK_H

#include <cstddef>
#include <cstdint>
#include <fstream>
#include <string>
#include <vector>

#include "detection.h"
// Свой `Function` студент пишет сам на занятии 3.2 и кладёт в src/ —
// этот каталог стоит на include-пути раньше комплекта.
#include "function.h"

namespace nano_edr {

// Куда уходит детект. Всё, что об этом знает движок.
using AlertSink = Function<void(const Detection&)>;

// --- получатель первый: консоль -------------------------------------------

// Печатает строку `[DETECT]` в stdout. Ровно то, что до этого занятия делал
// агент сам, — и это единственное, что от той печати осталось.
class ConsoleSink {
 public:
    void operator()(const Detection& detection) const;
};

// --- получатель второй: файл ----------------------------------------------

// Тот же формат, но в файл. Формат один и берётся из ToString(Detection):
// два получателя с двумя копиями формата разошлись бы на первой правке.
class FileSink {
 public:
    // Бросает std::runtime_error, если файл не открылся. Конструктор,
    // у которого нет канала для кода возврата, — занятие 2.1.
    explicit FileSink(const std::string& path);

    void operator()(const Detection& detection);

 private:
    std::ofstream out_;
};

// --- получатель третий: счётчик для тестов --------------------------------

// Куда счётчик пишет. Отдельная структура, а не поле получателя, по причине,
// которая на этом занятии всплывает первый раз: получатель хранится ВНУТРИ
// Function по значению, то есть тест отдаёт свою копию и больше её не видит.
// Значит наблюдаемое состояние должно жить снаружи, а получатель — только
// указывать на него. Тот же приём, что у трамплина на границе os.h: контекст
// передаётся указателем, владение остаётся у вызывающего.
// ЗАНЯТИЕ 3.3. Счётчик хранит снимок сработки, а не саму сработку.
//
// До этого занятия здесь лежал `std::vector<Detection>`, и это перестало
// компилироваться ровно тогда, когда сработка стала move-only: получатель
// принимает её константной ссылкой, а копировать теперь нельзя.
//
// Починка не в том, чтобы разрешить копирование обратно. Отказ компилятора
// здесь по делу: сработка — единичный факт, и второй её экземпляр означал бы
// второй доклад наверх. Счётчику же нужна не сработка, а возможность
// про неё спросить — и для этого хватает снимка из пяти полей.
//
// Улик в снимке нет намеренно: они дороги, а проверять их так всё равно
// неудобно — для этого есть тесты планировщика, которому улики и нужны.
struct SeenAlert {
    std::string rule;
    Severity severity = Severity::kLow;
    Timestamp ts;
    std::string pid;
    std::vector<std::string> actions;
};

struct AlertCounter {
    std::size_t total = 0;
    std::vector<SeenAlert> seen;
};

class CountingSink {
 public:
    explicit CountingSink(AlertCounter* counter) : counter_(counter) {}

    void operator()(const Detection& detection) const;

 private:
    AlertCounter* counter_;  // не владеет
};

// --- получатель, раздающий нескольким -------------------------------------

// Один получатель снаружи, несколько внутри.
//
// Движок и сам раздаёт детект всем подписанным, так что для простой раздачи
// этот класс не нужен. Нужен он там, где перед несколькими получателями должна
// стоять одна политика: подавление дубликатов с одним окном и одним счётчиком
// на всех, а не с тремя независимыми.
class FanOutSink {
 public:
    void Add(AlertSink sink);

    void operator()(const Detection& detection) const;

    std::size_t size() const { return sinks_.size(); }

 private:
    std::vector<AlertSink> sinks_;
};

// --- получатель, подавляющий дубликаты ------------------------------------

// Пропускает первый детект пары «правило + процесс» и молчит про остальные,
// пока не выйдет окно.
//
// Задача не косметическая. Сценарий ransomware даёт сорок детектов правила
// `ransom_extension` на один и тот же процесс за шесть секунд — это одна
// атака, и сорок строк про неё мешают увидеть остальные три. Настоящий агент
// схлопывает их в одну.
//
// Потеря при этом настоящая: по одной строке не видно, что зашифровано сорок
// файлов. Поэтому подавленные считаются и попадают в сводку — молча терять
// информацию хуже, чем терять её с отчётом.
class DedupSink {
 public:
    // inner — куда пропускать; window_ms — на сколько замолкать; suppressed —
    // куда считать подавленные, может быть nullptr.
    DedupSink(AlertSink inner, uint64_t window_ms, std::size_t* suppressed);

    void operator()(const Detection& detection);

 private:
    struct Seen {
        std::string rule;
        std::string pid;
        Timestamp ts;
    };

    AlertSink inner_;
    uint64_t window_ms_;
    std::size_t* suppressed_;  // не владеет
    std::vector<Seen> seen_;
};

}  // namespace nano_edr

#endif  // NANO_EDR_KIT_ALERT_SINK_H
