// RAII-обёртка над второй границей и получатель поверх неё. Занятие 3.2.
//
// os.h — вход: что система сообщила. edr.h — выход: что агент доложил наверх.
// Обёртка устроена так же, как OsHandle с занятия 2.1, и это сделано
// намеренно: приём осваивается один раз, а второй раз — узнаётся.
//
// Различия только там, где различается смысл:
//
//   конструктор -> исключение    канала нет — работать наполовину бессмысленно
//   Send        -> edr_status    отказ сети штатен, и бросать на нём нельзя
//   Flush       -> edr_status    то же
//   Config      -> строка        нет значения — не ошибка, а «своё умолчание»
//   деструктор  -> ничего        edr_free не бросает
//
// Send возвращает код по той же причине, по которой Wait возвращал его
// на 2.1: EDR_OFFLINE и EDR_BUSY — не ошибки программы, а состояние сети.
// Агент, падающий из-за недоступного сервера, защищает хост хуже, чем агент,
// который об этом сообщил и продолжил.
//
// ПОЧЕМУ EdrSink ЗДЕСЬ, А НЕ В alert_sink.h
//
// Потому что он единственный из получателей знает про границу. Остальные три
// не знают ни про edr.h, ни про os.h, и держать их в файле, который тянет
// за собой C-заголовок, значило бы навязать эту зависимость всем.

#ifndef NANO_EDR_KIT_EDR_HANDLE_H
#define NANO_EDR_KIT_EDR_HANDLE_H

#include <string>

#include "detection.h"
#include "edr.h"

namespace nano_edr {

class EdrHandle {
 public:
    // Зовёт edr_init. Бросает std::runtime_error, если тот не вернул EDR_OK.
    explicit EdrHandle(const std::string& config_path);

    // Зовёт edr_free: тот сам сбрасывает накопленное. Не бросает.
    ~EdrHandle();

    EdrHandle(const EdrHandle&) = delete;
    EdrHandle& operator=(const EdrHandle&) = delete;

    // Отправка сообщения. Строки внутри msg должны быть действительны только
    // на время вызова — реализация копирует всё, что ей нужно.
    edr_status Send(const edr_message& msg);

    // Гарантирует, что принятое дошло. В симуляторе но-оп, но звать перед
    // завершением обязательно: реализация поверх сети будет копить пачками,
    // и «у меня всё работало» кончится потерянными детектами.
    edr_status Flush();

    // Значение конфигурации от сервера. Если сервер ключа не давал
    // (EDR_NO_CONFIG) — возвращается fallback, и это не ошибка: смысл ответа
    // ровно «пользуйся своим умолчанием».
    std::string Config(const std::string& key, const std::string& fallback);

 private:
    edr_handle* handle_ = nullptr;
};

// Четвёртый получатель: детект уходит наверх.
//
// Он и есть доказательство того, что абстракция получателя рабочая. Устроен
// совершенно иначе остальных трёх — C-структура, массив ключ-значение, код
// возврата вместо исключения, — и встал на место без единой правки в движке.
class EdrSink {
 public:
    explicit EdrSink(EdrHandle* edr) : edr_(edr) {}

    void operator()(const Detection& detection) const;

 private:
    EdrHandle* edr_;  // не владеет: канал живёт дольше получателя
};

}  // namespace nano_edr

#endif  // NANO_EDR_KIT_EDR_HANDLE_H
