// Окно последних событий — односвязный список.
//
// Зачем список, когда есть std::vector. Затем, что на занятии 1.2 разбирается
// владение: узел владеет следующим, список владеет головой, а обход идёт
// по невладеющим указателям. Вектор всё это скрывает, и посмотреть на цепочку
// владения становится негде. С занятия Ф1 список действительно заменяется
// стандартным контейнером, и там же замеряется, что от этого изменилось.
//
// Это агрегат: поля открыты, методов нет. Единственное исключение —
// деструктор, и он не роскошь, а требование: см. ниже.
//
// К занятию 2.1 у списка появятся приватные поля, инвариант «size равен числу
// узлов» и методы вместо свободных функций. Разница между «структурой, за
// которой следит вызывающий» и «типом, который следит за собой сам», станет
// видна на своём же коде.

#ifndef NANO_EDR_KIT_EVENT_LIST_H
#define NANO_EDR_KIT_EVENT_LIST_H

#include <cstddef>
#include <memory>

#include "event.h"

namespace nano_edr {

// Узел владеет следующим узлом. Тип поля говорит об этом прямо.
struct EventNode {
    Event event;
    std::unique_ptr<EventNode> next;
};

// Список владеет головой; tail — невладеющий наблюдатель.
//
// Деструктор обязателен, и обязателен именно с явным циклом. Если его
// не написать, цепочка unique_ptr разбирается рекурсией: ~EventList уничтожает
// head, тот уничтожает своё поле next, и так до конца списка. Глубина рекурсии
// равна длине списка, и на десятках тысяч узлов это переполняет стек — причём
// не при работе со списком, а при его уничтожении, что делает диагностику
// особенно неприятной. Правило из лекции 2: если узлы владеют друг другом
// по цепочке, разбирать её обязан сам список.
struct EventList {
    std::unique_ptr<EventNode> head;
    EventNode* tail = nullptr;

    std::size_t size = 0;

    // Сколько событий держать. Ноль означает «без ограничения»: так список
    // годится и как окно, и как обычное хранилище — тестам нужно и то, и то.
    std::size_t capacity = 0;

    ~EventList();
};

// Дописывает копию события в конец.
//
// Если capacity задана и список полон, сначала выбрасывается самое старое
// событие: список — окно последних, а не архив. Значит после вызова
// size <= capacity всегда, и это то, что проверяют тесты.
void ListPushBack(EventList* list, const Event* event);

// Убирает самое старое событие. На пустом списке — ничего не делает
// и не считается ошибкой: «убрать из пустого» это обычный ход событий,
// а не исключительная ситуация.
void ListPopFront(EventList* list);

// Освобождает всё. После вызова список пуст и пригоден к использованию снова.
void ListClear(EventList* list);

}  // namespace nano_edr

#endif  // NANO_EDR_KIT_EVENT_LIST_H
