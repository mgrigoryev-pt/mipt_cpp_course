// Модель сущностей. Занятия 3.2 и Ф1.
//
// До этого занятия агент помнил только последние события — кольцевой буфер
// на 256 мест. Этого хватает, чтобы ответить «что было секунду назад»,
// и не хватает ни на один вопрос про связи: кто чей родитель, кто записал
// этот файл, откуда взялся этот процесс.
//
// Вопросы эти не выдуманные. Детект без цепочки предков бесполезен: аналитик
// видит «wscript.exe вышел в сеть» и первым делом спрашивает, кто его запустил.
// А реагирование на занятии 3.3 без модели вообще невозможно — убить надо
// поддерево процессов, а не один процесс, и изолировать файл-источник,
// а не тот, который попался в событии.
//
// ЧТО ИЗМЕНИЛОСЬ НА ЗАНЯТИИ Ф1
//
// Три вещи, и все три — следствия одного замера.
//
//   личность процесса        ключ записи — пара (pid, start), а не номер.
//                            До Ф1 `process_start` с уже известным номером
//                            затирал прежнюю запись вместе с её цепочкой;
//   хранилище                словари вместо векторов с линейным поиском;
//   вытеснение               по возрасту и по объёму, на тике os_wait,
//                            и об этом печатается в сводке.
//
// Первое стало возможным из-за второго: пара как ключ требует словаря
// и специализации `std::hash`, а словарей до лекции 13 не было. Третье стало
// НЕОБХОДИМЫМ из-за первого: пока номер затирал номер, размер модели был
// ограничен числом номеров сам собой. Теперь каждое новое воплощение — новая
// запись, и на нагрузочном журнале их сто шестьдесят тысяч вместо четырёх.
//
// Это стоит заметить отдельно. Исправление ошибки увеличило потребление
// памяти. Так бывает часто, и «зато правильно» здесь не ответ: агент, съевший
// память хоста, защищает его хуже, чем агент с путаницей в номерах. Отсюда
// и требование занятия — вытеснение, а не «предел на всякий случай».
//
// ЧТО МОДЕЛЬ ЗНАЕТ И ЧЕГО НЕ ЗНАЕТ
//
// Только то, что видела в потоке. Процессы, существовавшие до подписки,
// известны ей ровно настолько, насколько попали в события: pid встретился —
// запись появилась, а image и ppid остались пустыми, потому что их никто
// не сообщал. Поэтому цепочка предков обрывается там, где обрывается знание
// потока, и в выводе это видно: `880>1042(cmd.exe)`.
//
// Спросить у системы (`os_process_info`) модель не пытается, и это выбор,
// а не упущение: у обращений к границе есть бюджет (`max_os_queries`),
// и тратить его на историю — решение занятия 3.3, где появится реагирование
// и обращения к границе станут неизбежны.
//
// ПОРЯДКА У СЛОВАРЯ НЕТ, И ЭТО ВИДНО СНАРУЖИ
//
// Самая неприятная часть перехода на `unordered_map`, и заметить её надо
// до первого прогона, а не после. Обход хеш-таблицы идёт в порядке, который
// стандарт не определяет: он зависит от реализации, от числа корзин, от
// истории вставок. Значит любой результат, который получается обходом
// и уходит наружу — в вывод, в план реагирования, в эталон, — обязан быть
// упорядочен явно.
//
// В этом заголовке таких функций три: GetProcessTree, GetFilesCreatedBy
// и FindSpawnSource. У всех трёх в описании сказано, по чему именно они
// упорядочены. Это не украшение подписи, это часть контракта: эталоны
// сценариев сравниваются побайтово, и агент, у которого поддерево на MSVC
// и на g++ выходит в разном порядке, эталоном не проверяется вообще.

