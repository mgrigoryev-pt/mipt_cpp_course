// Запись окна. Занятие 3.3.
//
// ЧТО ОКНО ХРАНИТ И ПОЧЕМУ НЕ СОБЫТИЕ ЦЕЛИКОМ
//
// Кольцевой буфер лежит в объекте — `std::array` внутри, — а `std::array<T, N>`
// требует, чтобы T создавался по умолчанию. У `Event` конструктора
// по умолчанию нет и быть не должно: у него инвариант, введённый на занятии
// 2.1, и «пустое событие» этому инварианту противоречит.
//
// Разрешается это не отменой инварианта, а тем, что в окно кладётся ровно
// то, что нужно для печати контекста. Полное событие там и не требовалось.
//
// ПОЧЕМУ ИМЕННО ЗДЕСЬ НАПИСАНЫ ВСЕ ПЯТЬ
//
// Это единственный тип в проекте, у которого копирующий и перемещающий
// конструкторы написаны руками. Причина одна: их надо посчитать.
//
// Счётчика «копий вообще» не существует. Единственный способ узнать,
// копируется что-то или перемещается, — написать конструкторы самому
// и поставить в них по инкременту. Из этого следует неприятное, и об этом
// стоит сказать прямо: измеряя, мы меняем измеряемое. Написанные руками
// пять функций у компилятора уже не те, что сгенерированные: он не будет
// считать их тривиальными, а значит vector потеряет право переносить массив
// таких записей одним memcpy при росте.
//
// Здесь это не важно — записи лежат в std::array внутри объекта, который
// не растёт вообще. В другом месте было бы важно, и это ровно то, за что
// инструменты измерения ругают: замер меняет то, что замеряет. Хороший
// замер — тот, про чьё влияние вы можете сказать, велико оно или нет,
// а не тот, у которого влияния нет.
//
// Сравните с Event в event.h: там пять функций НЕ написаны, и по той же
// причине наоборот — их не надо считать, а компилятор сгенерирует лучше.
// Правило пяти и правило нуля — не два стиля, а два разных случая, и здесь
// они лежат в соседних файлах.
//
// НА ЧТО СМОТРЕТЬ В ЗАМЕРЕ
//
// До занятия 3.3 агент собирал запись и звал `PushBack(entry)`, то есть
// копировал: две строки на каждое событие. Теперь `PushBack(std::move(entry))`.
// В счётчике это видно как перенос из window_copied в window_moved, один
// в один, без остатка — а если остаток есть, значит какой-то путь
// в HandleEvent остался старым.

#ifndef NANO_EDR_KIT_WINDOW_ENTRY_H
#define NANO_EDR_KIT_WINDOW_ENTRY_H

#include <string>
#include <utility>

#include "copy_stats.h"
#include "event.h"

namespace nano_edr {

struct WindowEntry {
    Timestamp ts;
    std::string type;
    std::string pid;

    WindowEntry() = default;
    ~WindowEntry() = default;

    WindowEntry(const WindowEntry& other)
        : ts(other.ts), type(other.type), pid(other.pid) {
        ++copy_stats().window_copied;
    }

    WindowEntry& operator=(const WindowEntry& other) {
        // Проверка на самоприсваивание не нужна: строки её делают сами,
        // а ставить её здесь значило бы утверждать, что она нужна.
        ts = other.ts;
        type = other.type;
        pid = other.pid;
        ++copy_stats().window_copied;
        return *this;
    }

    // noexcept обязателен по существу, а не по обычаю: без него контейнер,
    // которому нужна гарантия «перенос не бросит», выберет копирование.
    // Здесь контейнер — std::array, ему всё равно; в векторе разница была бы
    // в разы, и написать noexcept проще, чем помнить, где именно оно важно.
    //
    // Он же и верен: у Timestamp move тривиален, у std::string move не бросает.
    WindowEntry(WindowEntry&& other) noexcept
        : ts(other.ts), type(std::move(other.type)), pid(std::move(other.pid)) {
        ++copy_stats().window_moved;
    }

    WindowEntry& operator=(WindowEntry&& other) noexcept {
        ts = other.ts;
        type = std::move(other.type);
        pid = std::move(other.pid);
        ++copy_stats().window_moved;
        return *this;
    }
};

}  // namespace nano_edr

#endif  // NANO_EDR_KIT_WINDOW_ENTRY_H
