// Счётчик копий. Занятия 3.3 и 4.3.
//
// Инструмент, а не часть агента. Нужен ровно для того, чтобы разговор
// про move-семантику шёл на числах.
//
// ЗАЧЕМ ОН ВООБЩЕ НУЖЕН
//
// Про копирование удобно рассуждать и невозможно угадать. «Здесь наверное
// копия» и «здесь наверное move» — предположения одинакового качества,
// а лекция 11 требует другого: показать место, где раньше была копия,
// и доказать, что теперь её нет. Доказать это можно только счётчиком.
//
// ЧТО СЧИТАЕТСЯ
//
// Не «копии объектов вообще» — такого счётчика не существует, — а копии
// в тех немногих местах, через которые проходит каждое событие:
//
//   строки внутри Event      четыре поля шапки плюс по две на каждое поле;
//   записи окна              то, что кладётся в кольцевой буфер;
//   события-улики            то, что попадает в сработку.
//
// Считать std::string изнутри нельзя: это чужой тип, конструкторов у него
// не перехватить. Поэтому счётчик стоит там, где копия делается НАМИ, —
// в наших конструкторах, которые эти строки копируют или перемещают.
// Инструмент показывает нашу работу, а не работу стандартной библиотеки,
// и это честнее, чем кажется: убрать мы можем только свои копии.
//
// ПОЧЕМУ ОН НЕ ПОД #ifdef
//
// Соблазн спрятать счётчик за макрос и включать только для замера сильный.
// Отказ сознательный, по двум причинам.
//
// Во-первых, инкремент неатомарного uint64_t рядом с созданием десятка
// std::string не измеряется вообще: одна аллокация дороже сотни таких
// инкрементов. Мерить смысла нет, а платить нечем.
//
// Во-вторых, замер, который делается в особой сборке, делается один раз
// и врёт со следующей правки. Счётчик, который есть всегда, печатается
// по флагу `--copies` и проверяется тестом, ловит возврат копии обратно —
// а именно это и происходит, когда через месяц кто-то добавит в горячий
// путь ещё один `push_back` по значению.
//
// ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ
//
// Атомарности. Счётчик неатомарный, и на занятии 4.3, когда события начнут
// приходить из другого потока, это станет гонкой — настоящей, с UB.
// Починка там будет вместе со всей остальной синхронизацией; чинить заранее
// то, чего ещё нет, значит писать `std::atomic` без причины и объяснять
// его за четыре занятия до лекции про потоки.
//
// ЧТО ИЗМЕНИЛОСЬ НА ЗАНЯТИИ 4.3
//
// Счётчик стал атомарным, и предупреждение из абзаца выше сбылось буквально.
//
// В режиме `delivery = thread` события собираются в колбэке, то есть
// на потоке доставки, а окно и улики — на потоке обработки. Значит
// event_strings_* пишет один поток, а читает другой, и до 4.3 это было
// неопределённым поведением: неатомарный uint64_t, изменяемый из двух
// потоков, — гонка данных по букве стандарта, а не «просто иногда неточное
// число». ThreadSanitizer сообщает о ней первым же прогоном.
//
// Починка — одна строка на счётчик: std::atomic<uint64_t> вместо uint64_t.
// Но интереснее не она, а порядок памяти.
//
// ПОЧЕМУ relaxed, А НЕ УМОЛЧАНИЕ
//
// Умолчание у атомиков — seq_cst, самый строгий порядок: каждая операция
// становится точкой синхронизации между потоками. Здесь это не нужно
// и стоит денег.
//
// Порядок памяти нужен, когда через атомик передают ПРАВО доступа к другим
// данным: «я записал буфер, потом выставил флаг; кто увидел флаг — увидит
// и буфер». Счётчик копий ничего никому не передаёт. Его читают один раз,
// в конце прогона, когда потока доставки уже нет; между его значением
// и любыми другими данными нет отношения «увидел это — значит увидел и то».
//
// Для такого случая и существует memory_order_relaxed: атомарность
// без синхронизации. Инкремент не потеряется, но и барьером не станет.
//
// ЧТО ПРИ ЭТОМ ОСТАЛОСЬ НЕВЕРНЫМ, И ЭТО ЧЕСТНО
//
// Сумма total() читает пять счётчиков подряд, и снимок получается
// несогласованным: между чтением первого и последнего они могли измениться.
// Чинить это нечем, кроме замка, а замок ради строки в отчёте — плохой
// размен. Печатается сводка после остановки доставки, когда писать некому,
// так что практического значения у неоднородности снимка здесь нет.

#ifndef NANO_EDR_KIT_COPY_STATS_H
#define NANO_EDR_KIT_COPY_STATS_H

#include <atomic>
#include <cstdint>

namespace nano_edr {

// Счётчик, который можно увеличивать из двух потоков.
//
// Отдельный тип, а не std::atomic<uint64_t> прямо в полях, по двум причинам.
// Первая: порядок памяти задаётся один раз здесь, а не двенадцать раз
// в местах вызова — иначе кто-нибудь однажды напишет `+= 1` с умолчанием
// и получит seq_cst на горячем пути. Вторая: `++счётчик` и `счётчик += n`
// в местах вызова читаются ровно так же, как читались до 4.3, и переход
// на атомики не превратился в правку двадцати строк по всему проекту.
class Counter {
 public:
    Counter& operator++() {
        value_.fetch_add(1, std::memory_order_relaxed);
        return *this;
    }

    Counter& operator+=(uint64_t delta) {
        value_.fetch_add(delta, std::memory_order_relaxed);
        return *this;
    }

    uint64_t get() const { return value_.load(std::memory_order_relaxed); }

    void Reset() { value_.store(0, std::memory_order_relaxed); }

    // Сравнение с числом — ради выданных тестов занятия 3.3, которые пишут
    // `CHECK(copy_stats().window_copied == 0)` и обязаны продолжать
    // собираться. Проверяют они move-семантику, а она на 4.3 никуда
    // не делась: тест, отключённый из-за смены типа счётчика, был бы
    // покрытием, потерянным на ровном месте.
    //
    // Оператор не член: тогда `0 == counter` работает так же, как
    // `counter == 0`. Обратное сравнение и != C++20 выводит сам.
    friend bool operator==(const Counter& counter, uint64_t value) {
        return counter.get() == value;
    }

 private:
    std::atomic<uint64_t> value_{0};
};


struct CopyStats {
    // Строки, скопированные при сборке Event из EventParts. Пишется
    // на потоке доставки — отсюда и атомарность.
    Counter event_strings_copied;
    // Те же строки, но перемещённые.
    Counter event_strings_moved;

    // Записи окна: копия — это PushBack(const T&), move — PushBack(T&&).
    // Пишется на потоке обработки.
    Counter window_copied;
    Counter window_moved;

    // События, скопированные в улики сработки.
    Counter evidence_copied;

    // Снимок несогласованный: пять чтений подряд. См. заголовок файла.
    uint64_t total() const {
        return event_strings_copied.get() + window_copied.get() +
               evidence_copied.get();
    }

    void Reset() {
        event_strings_copied.Reset();
        event_strings_moved.Reset();
        window_copied.Reset();
        window_moved.Reset();
        evidence_copied.Reset();
    }
};

// Один счётчик на программу. Глобальное изменяемое состояние — плата
// за то, что инструмент не должен просачиваться в подписи: если бы каждый
// конструктор Event принимал ссылку на счётчик, инструмент стал бы частью
// дизайна, а он не часть дизайна.
CopyStats& copy_stats();

// Обнуление. Нужно тестам: два замера в одном процессе иначе складываются.
void ResetCopyStats();

}  // namespace nano_edr

#endif  // NANO_EDR_KIT_COPY_STATS_H
