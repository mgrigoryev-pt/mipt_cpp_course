#ifndef NANO_EDR_KIT_RULE_TEXT_H
#define NANO_EDR_KIT_RULE_TEXT_H

#include <cstdint>
#include <memory>
#include <string>
#include <string_view>

#include "conditions.h"
#include "rules.h"

namespace nano_edr {

// Обрезать пробелы, табуляции и возврат каретки с обоих концов.
//
// Возвращённый взгляд смотрит внутрь text и живёт ровно столько же.
std::string_view Trim(std::string_view text);

// Целое без знака целиком: "10" — да, "10x" и "" — нет.
bool ParseUint(std::string_view text, uint64_t* out);

// low | medium | high | critical. false — слово не то, и диагностику
// формулирует вызывающий: у него есть номер строки, здесь его нет.
bool ParseSeverity(std::string_view text, Severity* out);

// Собрать одно условие из строки «поле оператор значение».
//
// Альтернативы внутри строки разделяются словом `or` и означают ИЛИ; слово
// внутри кавычек разделителем не считается. Операторы: is (только для поля
// type), equals, contains, ends_with.
//
// nullptr означает отказ, и тогда *error несёт сообщение без номера строки:
// строку знает вызывающий. Сообщения здесь ровно те, которых ждут выданные
// тесты, — «неизвестный оператор: ...», «неизвестный тип события: ...»,
// «оператор is применим только к полю type», «условие не разбирается: ...».
std::unique_ptr<ICondition> BuildCondition(std::string_view text,
                                           std::string* error);

}  // namespace nano_edr

#endif  // NANO_EDR_KIT_RULE_TEXT_H
