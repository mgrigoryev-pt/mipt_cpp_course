// на проверке. Первое: `type is a or b` собирается в одно условие со
// списком, а не в ИЛИ из трёх. Второе: смешивать `type is` с остальными
// операторами в одной строке запрещено, потому что смысл такой строки
// неоднозначен, а неоднозначную конфигурацию лучше отвергнуть, чем угадать.
