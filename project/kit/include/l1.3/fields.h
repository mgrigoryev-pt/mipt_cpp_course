// Функции доступа к полям события.
//
// Здесь сосредоточен главный вопрос занятия: чем функция сообщает вызывающему,
// что не справилась. Ответ не один на всю программу, и это не небрежность —
// у разных отказов разная природа:
//
//   поля нет в событии          -> nullptr. Это один из двух ожидаемых исходов,
//                                  а не поломка: у file_write нет поля domain,
//                                  и спрашивать про него законно.
//   строка журнала битая         -> bool или счётчик. Битые строки бывают
//                                  всегда.
//   нет обязательного поля      -> исключение. Нарушен контракт формата: если
//                                  у process_start нет image, дальше идти
//                                  некуда, и продолжать на пустой строке —
//                                  значит прятать ошибку.
//   индекс за границами         -> исключение. Ошибка в коде, а не в данных;
//                                  в этом занятии не нужен — функций
//                                  с индексом здесь нет.
//
// Правило, которое стоит вынести с этого занятия: **способ сообщить
// об ошибке — часть сигнатуры**, и выбирается он один раз на всю группу
// функций, а не по настроению в каждой. Функции доступа к полям возвращают
// значения; функция, которая требует обязательного поля, бросает.
// Смешивать оба в одной функции — верный способ получить код, который
// вызывающий не умеет использовать правильно.
//
// И последний рубеж: в main стоит catch (const std::exception&). Программа
// обязана сказать, что пошло не так, а не умереть молча.

#ifndef NANO_EDR_KIT_FIELDS_H
#define NANO_EDR_KIT_FIELDS_H

#include <cstdint>
#include <string>

#include "event.h"

namespace nano_edr {

// ---------------------------------------------------------------------------
// Доступ к полям
// ---------------------------------------------------------------------------

// Значение поля или nullptr, если поля нет. При повторяющихся ключах — первое
// вхождение.
//
// Ищет только среди fields. Шапка события — ts, type, pid — лежит отдельными
// полями и доступна напрямую, и особого случая для этих трёх ключей здесь нет
// намеренно: иначе у одних и тех же данных окажется два пути доступа,
// и читающему код придётся помнить, что ровно три ключа ведут себя
// не как все.
//
// Возвращается указатель, а не копия: копировать строку только чтобы посмотреть
// на неё — расточительство, а событий будет два миллиона. Указатель
// действителен столько же, сколько само событие.
const std::string* FindField(const Event& event, const std::string& key);

// Значение обязательного поля.
//
// Бросает std::invalid_argument, если поля нет: раз оно объявлено обязательным,
// его отсутствие — нарушение контракта формата, и вернуть пустую строку значило
// бы соврать вызывающему. Сообщение исключения называет поле: диагностика,
// по которой нельзя найти причину, — половина диагностики.
const std::string& GetRequiredField(const Event& event, const std::string& key);

// Целое из поля.
//
// Возвращает false, если поля нет или оно не разбирается как целое. Второе
// бывает не реже первого: значение приходит из внешнего источника,
// и «size=абв» — битые данные, а не ошибка программы.
bool GetIntField(const Event& event, const std::string& key, uint64_t* out);

// Перегрузка со значением по умолчанию — для полей, отсутствие которых
// осмысленно: у события без ppid родителя просто нет.
uint64_t GetIntField(const Event& event, const std::string& key,
                     uint64_t fallback);

// ---------------------------------------------------------------------------
// Предикаты
// ---------------------------------------------------------------------------
//
// Каждый отвечает на один вопрос о событии и ничего не печатает. Из них
// собираются правила для таблицы из rules.h, а на занятии 2.1 те же вопросы
// станут функторами-условиями.

bool IsProcessStart(const Event& event);
bool IsFileWrite(const Event& event);
bool IsNetConnect(const Event& event);

// Путь из поля path заканчивается на suffix. Сравнение без учёта регистра:
// в файловой системе Windows «A.JS» и «a.js» — один файл, и правило, которое
// этого не знает, обходится переименованием.
bool PathEndsWith(const Event& event, const std::string& suffix);

// Подстрока в командной строке. Тоже без учёта регистра и по той же причине.
bool CommandLineContains(const Event& event, const std::string& needle);

// Приведение пути к сравнимому виду: всё в нижний регистр, разделитель —
// обратный слеш, идущие подряд разделители склеиваются в один, %TEMP%
// и %TMP% раскрываются в \appdata\local\temp. Возвращается новая строка,
// исходная не меняется. Форму результата сверяют выданные тесты:
//
//   C:/Users/Max/A.JS      -> c:\users\max\a.js
//   C:\work\\build\a.obj   -> c:\work\build\a.obj
//   %TEMP%\a.js            -> \appdata\local\temp\a.js
//   %WINDIR%\x             -> %windir%\x   (раскрываются только TEMP и TMP)
//
// Раскрытие каноническое: из окружения %TEMP% не читается, журнал записан
// на чужой машине и настоящего пути в нём нет. Смысл замены один — чтобы путь
// с %TEMP% и полный путь до Temp содержали одинаковый кусок
// \appdata\local\temp\, по которому правило и узнаёт временный каталог.
//
// Дальше этого нормализация не идёт: симлинки, короткие имена вида PROGRA~1
// и точки внутри пути остаются как есть. Полную нормализацию путей за одно
// занятие не написать, и честнее сказать, где она кончается, чем делать вид,
// что задача решена целиком.
std::string NormalizePath(const std::string& path);

}  // namespace nano_edr

#endif  // NANO_EDR_KIT_FIELDS_H
