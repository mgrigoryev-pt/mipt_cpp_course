// Реагирование: план и его исполнение. Занятие 3.3.
//
// ПОЧЕМУ ЭТО ДВА КЛАССА, А НЕ ОДИН
//
// Соблазн написать один класс, который по сработке сам всё убьёт, большой,
// и разделение выглядит бюрократией. Оно не бюрократия, и вот проверка:
// режим `--dry-run` печатает план и ничего не делает. Если план — это объект,
// dry-run состоит в том, чтобы его не исполнять. Если плана как объекта нет,
// dry-run приходится размазывать по коду исполнения: `if (!dry_run) kill(...)`
// в каждом месте, где что-то делается, и достаточно забыть один такой if,
// чтобы «печать плана» кого-нибудь убила.
//
// Второе следствие того же разделения важнее первого: ResponsePlanner
// не знает про os.h вообще. Он читает модель и возвращает вектор структур.
// Значит его можно проверить тестом без симулятора, без границы, без
// побочных эффектов — просто «вот модель, вот сработка, вот ожидаемый план».
// Ровно это и делают выданные тесты занятия.
//
// ЧТО ТАКОЕ ПЛАН
//
// Список целей, каждая со своим действием и причиной. Целей ровно три вида,
// и все три из требования занятия:
//
//   убить поддерево процессов      атака живёт в потомках, а не только в pid,
//                                  на котором сработало правило;
//   изолировать файл-источник      тот файл, из которого процесс запущен:
//                                  пока он лежит на диске, атаку повторят;
//   удалить созданные файлы        то, что процесс принёс с собой.
//
// Порядок в плане не случаен: сначала убить, потом трогать файлы. Живой
// процесс держит свои файлы открытыми, и удаление вернёт OS_BUSY. Это
// не догадка — симулятор умеет отвечать OS_BUSY, и сценарий с этим ответом
// в комплекте есть.
//
// ЛОВУШКА, В КОТОРУЮ ЛЕГКО ПОПАСТЬ
//
// «Удалить созданные файлы» звучит однозначно, пока не посмотришь, что
// считается созданным. Шифровальщик переименовывает документы: был
// `quarterly.xlsx`, стал `quarterly.xlsx.locked`. В модели появляется новая
// запись, и её создателем честно записан шифровальщик — он и создал этот
// путь. Планировщик, который удаляет всё созданное, удалит сорок файлов
// с данными жертвы. Единственную копию, которая у неё осталась.
//
// Поэтому у записи о файле есть признак `from_move`, и удаляются только
// файлы, которых до процесса не существовало. Переименованное — это чьи-то
// данные под другим именем, а не принесённый груз.
//
// ЧТО ДЕЛАЕТ ДЕДУПЛИКАЦИЯ И ПОЧЕМУ ЕЁ ДВЕ
//
// Внутри плана: одна цель — одно действие. Файл-источник процесса часто
// им же и создан, и без дедупликации он попал бы в план дважды — на изоляцию
// и на удаление. Второе действие отменило бы первое.
//
// Между планами: на одну атаку срабатывает несколько правил. На phishing_macro
// их пять, и три из них — про один и тот же процесс. Пять планов, в каждом
// «убить 1101». Первый убьёт, остальные четыре получат OS_NO_SUCH_PROCESS
// и потратят по обращению к системе из бюджета сценария. Поэтому исполнитель
// помнит, что уже сделал, и повторов не повторяет.
//
// Обе нужны, и ни одна не заменяет другую: первая работает по цели внутри
// одного плана, вторая — по цели за всё время работы агента.

#ifndef NANO_EDR_KIT_RESPONSE_H
#define NANO_EDR_KIT_RESPONSE_H

#include <cstddef>
#include <cstdint>
#include <string>
#include <unordered_set>
#include <vector>

#include "detection.h"
#include "entity_model.h"
#include "event.h"
#include "os.h"
#include "os_handle.h"

namespace nano_edr {

enum class ActionKind {
    kKillProcess,
    kQuarantineFile,
    kDeleteFile,
};

const char* ActionKindName(ActionKind kind);

// Одно действие плана.
//
// Агрегат, и намеренно: инварианта у него нет — заполняет его планировщик,
// а не чужой разбор строки. Пустой path у kKillProcess не «некорректное
// состояние», а «поле не про это действие».
struct Action {
    ActionKind kind = ActionKind::kKillProcess;

    // Для kKillProcess.
    std::string pid;
    // Время старта того процесса, который собирались убить. Ноль означает
    // «модель не знает» — и это не то же самое, что «не проверять»:
    // исполнитель на нуле спросит систему, а не махнёт рукой.
    Timestamp expected_start;

    // Для kQuarantineFile и kDeleteFile.
    std::string path;
    // Для kQuarantineFile: куда переносим.
    std::string to;

    // Почему цель в плане. Идёт в вывод: действие без причины невозможно
    // ни объяснить, ни оспорить.
    std::string reason;

    // Цель действия одной строкой — по ней и идёт дедупликация.
    const std::string& target() const {
        return kind == ActionKind::kKillProcess ? pid : path;
    }
};

std::string ToString(const Action& action);

class ResponsePlan {
 public:
    // Добавляет действие, если такой цели в плане ещё нет.
    // Возвращает false, если цель уже была: вызывающему это иногда нужно
    // знать, а чаще нет — тогда результат можно игнорировать.
    bool Add(Action action);

    bool Has(const std::string& target) const;

    const std::vector<Action>& actions() const { return actions_; }
    std::size_t size() const { return actions_.size(); }
    bool empty() const { return actions_.empty(); }

 private:
    std::vector<Action> actions_;
};

// Планировщик: сработка плюс модель — план.
//
// Про os.h не знает. Это его главное свойство, а не случайность.
class ResponsePlanner {
 public:
    // quarantine_dir — куда переносить изолированные файлы. Приходит
    // от сервера через edr_config_get; пустая строка означает «изоляция
    // недоступна», и тогда файл-источник в план не попадёт вообще.
    // Молча переносить в никуда хуже, чем не переносить.
    ResponsePlanner(const EntityModel* model, std::string quarantine_dir);

    // Возвращает план по значению. Копии здесь нет: возвращается локальный
    // объект, и компилятор построит его прямо в месте вызова (RVO, лекция 11).
    // Писать `return std::move(plan)` было бы не оптимизацией, а её
    // отменой — RVO бы не сработало. Именно на это ругается
    // -Wpessimizing-move, и в этом проекте он включён.
    ResponsePlan Plan(const Detection& detection) const;

    // Куда попадёт файл при изоляции. Отдельно, потому что это нужно тестам
    // и потому что правило именования — часть контракта, а не деталь.
    std::string QuarantinePath(const std::string& path,
                               const std::string& pid) const;

 private:
    const EntityModel* model_;
    std::string quarantine_dir_;
};

// Сколько чего получилось. Не для красоты: без этой таблицы «реагирование
// работает» — утверждение, которое нечем проверить.
//
// Счётчика «убито без проверки времени старта» здесь нет намеренно. Такого
// вызова у этого исполнителя не бывает: время старта берётся из модели, а если
// её знания не хватило — у системы, и при отказе действие не выполняется
// вовсе. Проверять это своим счётчиком было бы проверкой себя собой; проверяет
// это симулятор строкой `unsafe_kills` в отчёте, и сценарии требуют там нуля.
struct ResponseStats {
    std::size_t planned = 0;        // действий в планах, всего
    std::size_t skipped_repeat = 0; // отброшено как уже сделанное

    std::size_t killed = 0;
    std::size_t kill_gone = 0;      // OS_NO_SUCH_PROCESS: успел умереть сам
    std::size_t kill_reused = 0;    // OS_PID_REUSED: номер достался другому
    std::size_t kill_denied = 0;    // OS_ACCESS_DENIED: защищённый процесс

    std::size_t quarantined = 0;
    std::size_t deleted = 0;
    std::size_t file_busy = 0;      // OS_BUSY
    std::size_t file_gone = 0;      // OS_NO_SUCH_FILE
    std::size_t file_denied = 0;    // OS_ACCESS_DENIED

    std::size_t queries = 0;        // обращений к системе за временем старта
    std::size_t own_events = 0;     // событий, вызванных нами же

    std::size_t failed() const {
        return kill_gone + kill_reused + kill_denied +
               file_busy + file_gone + file_denied;
    }
};

// Исполнитель плана.
//
// Он же и журнал собственной активности — потому что знает о ней ровно он.
// Каждое действие агента порождает событие, которое агент увидит: убитый
// процесс даёт process_end, перенесённый файл даёт file_move. Правило,
// считающее переименования, сработает на карантине сорока файлов — агент
// сработает на себе.
//
// Узнаётся своё двумя способами, и второй нужен из-за первого.
//
//   по полю actor   события, порождённые нашим убийством, несут actor=<наш
//                   pid>. Больше их не несёт никто, так что первое же такое
//                   событие сообщает нам наш собственный номер — которого
//                   os.h не выдаёт никаким запросом;
//   по пути         файловые события actor не несут, зато путь в них тот
//                   самый, который мы только что трогали. До первого
//                   убийства это единственный способ.
//
// Порядок именно такой: сначала узнать номер, если получится, потом сверить
// путь. Обратный работал бы тоже, но медленнее — сравнение номера дешевле
// поиска по списку путей.
class Responder {
 public:
    // os может быть nullptr: у журнала, читаемого из файла, системы нет,
    // и реагировать не на чем. Это не ошибка и не повод отказываться
    // работать — план всё равно строится и печатается.
    Responder(OsHandle* os, bool dry_run);

    // Исполнить план. В dry-run печатает `[PLAN]` и не делает ничего.
    void Execute(const ResponsePlan& plan);

    // Вызвано ли это событие нами. Не const: на событии с actor исполнитель
    // узнаёт собственный pid и запоминает его.
    bool Recognize(const Event& event);

    const ResponseStats& stats() const { return stats_; }
    const std::string& self_pid() const { return self_pid_; }
    bool dry_run() const { return dry_run_; }

 private:
    // Время старта для убийства: из плана, а если там ноль — у системы.
    // Возвращает false, если и система не знает: процесса больше нет,
    // и убивать некого.
    bool ResolveStart(const std::string& pid, Timestamp planned,
                      uint64_t* out);

    void Kill(const Action& action);
    void MoveToQuarantine(const Action& action);
    void Delete(const Action& action);

    OsHandle* os_;
    bool dry_run_;
    std::string self_pid_;  // узнаётся из поля actor

    // ЗАНЯТИЕ Ф1. Два множества вместо двух векторов.
    //
    // Здесь важен не размер, а частота обращения. Recognize зовётся на КАЖДОМ
    // событии и проверяет, не наш ли это путь; с вектором это линейный поиск
    // по всем путям, которых мы касались, на каждое событие потока. Сработок
    // мало, поэтому множество маленькое, — и именно поэтому подмену легко
    // не заметить и оставить как есть.
    //
    // unordered_set, а не set: порядок не нужен ни разу, оба множества только
    // спрашивают «есть ли». Порядок здесь и не должен быть нужен — как только
    // из такого контейнера что-то печатают, это надо упорядочивать явно,
    // см. заголовок entity_model.h.
    std::unordered_set<std::string> done_;     // цели, по которым отработали
    std::unordered_set<std::string> touched_;  // пути, которых мы касались

    ResponseStats stats_;
};

}  // namespace nano_edr

#endif  // NANO_EDR_KIT_RESPONSE_H
