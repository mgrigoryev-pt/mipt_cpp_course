// Свой Function. Занятие 3.2, примитив.
//
// Задача одна: сложить в одну переменную любой вызываемый объект с подходящей
// подписью — свободную функцию, лямбду с захватом, объект с operator(), —
// и вызвать его, ничего не зная о его типе. Ровно это делает std::function,
// и ровно это здесь написано в двадцать пять строк.
//
// ЗАЧЕМ ЭТО ВООБЩЕ НУЖНО
//
// Шаблон занятия 3.1 умел другое. `AllOfStatic<A, B, C>` тоже хранит любые
// типы — но состав известен компилятору, и каждый набор даёт свой тип.
// Положить `AllOfStatic<A, B>` и `AllOfStatic<C>` в один вектор нельзя: типы
// разные. Получателей же детекта хочется именно вектором, и какие они будут —
// решается во время работы, по флагам командной строки.
//
// Значит нужен один тип, за которым может стоять что угодно. То же самое
// требование, что у ICondition на занятии 2.3, и решение то же — виртуальный
// вызов. Разница в том, что от вызываемого объекта не требуется наследовать
// ничей интерфейс: наследника делает за него шаблон. Приём называется
// стиранием типа (type erasure).
//
// ЧТО ЗА НЕГО ПЛАТИТСЯ
//
//   аллокация      — одна, на каждое присваивание; std::function умеет
//                    обходиться без неё для маленьких объектов, см. ниже;
//   виртуальный    — один на вызов, косвенность как у ICondition;
//   размер         — sizeof(Function) — один указатель, независимо от того,
//                    что внутри. Это и есть польза: тип перестал зависеть
//                    от содержимого.
//
// ЧЕМ ЭТО НЕ std::function
//
// Function перемещается, но не копируется: внутри unique_ptr. std::function
// копируется, и это дороже — требование копируемости заставляет хранить
// в таблице ещё и «склонировать себя», а вызываемый объект обязан быть
// копируемым, даже если его никто никогда не копирует.
//
// Плюс std::function делает small object optimization: маленький объект
// (обычно до 16 байт) лежит прямо в самом std::function, без аллокации.
// Здесь этого нет — и продвинутая часть занятия именно про то, чтобы
// подменить одно другим и посмотреть, где что выигрывает.

#ifndef NANO_EDR_KIT_FUNCTION_H
#define NANO_EDR_KIT_FUNCTION_H

#include <memory>
#include <utility>

namespace nano_edr {

// Объявлен, но не определён — как FieldTraits на занятии 3.1. Определена
// только частичная специализация ниже, и это заставляет писать Function
// с подписью в скобках: `Function<void(const Detection&)>`. Написать
// `Function<int>` не получится, и это правильно — такой тип бессмыслен.
template <typename Signature>
class Function;

template <typename R, typename... Args>
class Function<R(Args...)> {
 public:
    Function() = default;

    // Ловит любой вызываемый объект. Шаблонный конструктор, а не конструктор
    // от конкретного типа: типов бесконечно много, и в этом весь смысл.
    //
    // Аргумент по значению, а не по ссылке: копия всё равно понадобится —
    // объект должен пережить конструктор, — и брать по значению честнее,
    // чем брать по const& и копировать внутри.
    template <typename F>
    Function(F callable)                                       // NOLINT
        : holder_(std::make_unique<Holder<F>>(std::move(callable))) {}

    // Копирования нет: внутри unique_ptr. Перемещение компилятор напишет сам,
    // и этого достаточно — вектор получателей на нём и работает.

    R operator()(Args... args) const {
        return holder_->Call(args...);
    }

    // Пустой Function вызывать нельзя: внутри нулевой указатель. Проверять
    // до вызова — дело вызывающего, отсюда явное преобразование к bool.
    explicit operator bool() const { return holder_ != nullptr; }

 private:
    // Интерфейс без шаблонов — то, что вектор сможет хранить указателем.
    struct HolderBase {
        virtual ~HolderBase() = default;
        virtual R Call(Args... args) = 0;
    };

    // Наследник под конкретный вызываемый тип. Его и создаёт конструктор,
    // и только он знает, что внутри.
    template <typename F>
    struct Holder : HolderBase {
        explicit Holder(F callable) : callable_(std::move(callable)) {}

        R Call(Args... args) override { return callable_(args...); }

        F callable_;
    };

    std::unique_ptr<HolderBase> holder_;
};

}  // namespace nano_edr

// ПРО const У operator()
//
// operator() помечен const, а Call — нет, и это не описка. Так же устроен
// и std::function, и по той же причине: константность Function говорит
// «я не меняю сам Function», а не «я не меняю то, что внутри». Через
// `const std::unique_ptr<T>` объект по указателю остаётся неконстантным,
// поэтому неконстантный Call вызывается законно.
//
// Практическая польза прямая: получатель с состоянием — тот, что подавляет
// дубликаты и помнит, что уже отправил, — работает и через const-ссылку
// на Function. Плата за это — const у Function перестаёт что-либо обещать
// про содержимое, и знать это стоит.

#endif  // NANO_EDR_KIT_FUNCTION_H
