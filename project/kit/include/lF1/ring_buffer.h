// Кольцевой буфер. Занятие 3.1.
//
// Первая замена своего примитива своим же, более подходящим: на этом месте
// с занятия 1.2 стоял односвязный список. Список был правильным выбором тогда —
// на нём разбиралось владение, — и перестал быть правильным сейчас.
//
// Что даёт кольцевой буфер и чего не давал список:
//
//   не аллоцирует вообще        память в объекте, `std::array` внутри;
//   элементы лежат рядом        один проход по буферу — один проход по памяти,
//                               а не прыжки по узлам, разбросанным по куче;
//   вытеснение бесплатно        новый элемент пишется поверх самого старого,
//                               освобождать нечего.
//
// Чего он не даёт: размер задаётся на этапе компиляции. Это настоящая плата,
// а не мелочь: окно агента больше нельзя настроить произвольным числом
// из командной строки. Ровно тот размен, который нужно уметь называть словами.
//
// N — non-type параметр шаблона (лекция 8): размер попадает в тип, поэтому
// буферы разного размера — разные типы, и перепутать их нельзя.
//
// ЗАНЯТИЕ Ф1: ЭТОТ ПРИМИТИВ ОСТАЁТСЯ, И ЭТО РЕЗУЛЬТАТ ЗАМЕРА
//
// Занятие Ф1 заменяет свои структуры данных стандартными. Односвязный список
// из 1.2 уходит, линейный поиск в модели уходит, счётчики порогового правила
// переезжают в словарь. Кольцевой буфер остаётся — потому что замер сказал
// оставить, а не потому что жалко выбрасывать написанное.
//
// Два миллиона добавлений в окно на 256 мест, Release, g++-14 (разброс между
// прогонами до двадцати процентов, полный замер — в tasks/F1/exercise):
//
//   свой список            80 мс   2 000 000 аллокаций   160 МБ
//   свой кольцевой буфер   60 мс           0 аллокаций     0 Б
//   std::deque             55 мс     285 719 аллокаций   146 МБ
//   std::vector + erase  2250 мс          10 аллокаций    74 КБ
//
// Кольцевой буфер и `deque` различаются в пределах разброса, то есть
// не различаются. Список медленнее процентов на сорок, и вся разница —
// в аллокации узла на каждое событие. Вектор с `erase(begin())` медленнее
// в сорок пять раз: удаление из начала сдвигает весь остаток, и это то самое
// квадратичное поведение, про которое предупреждает лекция 13.
//
// То же на MSVC 19.44, и одна строка там другая:
//
//   свой список           135 мс   2 000 000 аллокаций   160 МБ
//   свой кольцевой буфер   57 мс           0 аллокаций     0 Б
//   std::deque             74 мс         520 аллокаций    45 КБ
//   std::vector + erase  2653 мс          15 аллокаций    69 КБ
//
// У `deque` пятьсот двадцать аллокаций вместо двухсот восьмидесяти пяти тысяч.
// Разница не в коде: `pop_front` у libstdc++ освобождает опустевший блок,
// у MSVC STL — оставляет его в своей карте и переиспользует. Обе реализации
// правы, стандарт этого не требует ни от одной.
//
// Отсюда и выбор. Довод «`deque` мало аллоцирует» непереносим — он верен
// на одной библиотеке и неверен на другой. Довод «кольцевой буфер не
// аллоцирует вообще» переносим, потому что это следствие устройства.
// А по времени `deque` не быстрее ни на одной из двух платформ: на g++
// неразличимо, на MSVC хуже. Поэтому выбор — кольцевой буфер.
//
// Для агента, который живёт неделями, ноль аллокаций это не то же самое,
// что «мало»: у длинных прогонов есть фрагментация, у аллокатора —
// блокировка, а на Ф3 появятся потоки.
//
// Есть и третье измерение, и там разрыв не в проценты: доступ
// к предпоследнему элементу стоит 0,5 нс у кольцевого буфера, 1,6 нс
// у `deque` и 316 нс у списка. Односвязный список не умеет ходить назад,
// и «взять предпоследний из 256» — это проход по 254 узлам в куче. Агент
// делает это на каждой сработке, когда печатает контекст.
//
// И самое полезное число здесь то, которого в таблице нет. Шестьдесят
// миллисекунд на два миллиона событий — это одна тысячная времени прогона
// агента в состоянии 3.3 (шестьдесят шесть секунд) и меньше процента даже
// после того, как всё остальное ускорилось восьмикратно. Окно не было узким
// местом никогда, и любой выбор в этой таблице, кроме вектора, не изменил бы
// ничего. Узкое место было в модели сущностей, и найти это можно было только
// замером.
//
// Когда решение придётся пересмотреть, известно заранее: размер окна задан
// на этапе компиляции, и как только его понадобится настраивать от сервера,
// на этом месте окажется `std::deque`. Это цена, названная ещё на 3.1,
// и она не изменилась.

#ifndef NANO_EDR_KIT_RING_BUFFER_H
#define NANO_EDR_KIT_RING_BUFFER_H

#include <array>
#include <cstddef>
#include <iterator>
#include <utility>

namespace nano_edr {

template <typename T, std::size_t N>
class RingBuffer {
 public:
    static_assert(N > 0, "кольцевой буфер нулевого размера ничего не хранит");

    // Обход в логическом порядке — от самого старого к самому новому.
    //
    // ЗАНЯТИЕ Ф1: ПОЧЕМУ ЗДЕСЬ ПЯТЬ ПСЕВДОНИМОВ ТИПОВ
    //
    // До Ф1 итератор был минимальный: `++`, `*`, `!=` — ровно то, что нужно
    // range-based for, и в комментарии было сказано «полноценные категории
    // итераторов — лекция 13». Лекция 13 пришла, и вместе с ней пришёл счёт.
    //
    // `std::count_if` не компилируется с таким итератором. Не потому, что ему
    // мало операций — операций хватает, — а потому, что он спрашивает
    // `std::iterator_traits<It>::difference_type`, а traits берёт этот тип
    // из самого итератора. Нет псевдонима — нет типа — нет алгоритма,
    // и сообщение компилятора говорит про difference_type, а не про то,
    // что итератор неполный.
    //
    // Пять псевдонимов ниже — это и есть «быть итератором» по определению
    // стандарта. Свой контейнер работает с алгоритмами ровно настолько,
    // насколько его автор об этом позаботился, и это ещё одна строка в цене
    // рукописного примитива: у стандартного контейнера такой строки нет.
    //
    // forward_iterator_tag, а не random_access: `+= n` этот итератор
    // не умеет, и заявлять категорию выше, чем поддерживаешь, — худшее
    // из возможных здесь решений. Алгоритм поверит и будет прыгать.
    class Iterator {
     public:
        using iterator_category = std::forward_iterator_tag;
        using value_type = T;
        using difference_type = std::ptrdiff_t;
        using pointer = const T*;
        using reference = const T&;

        // Конструктор по умолчанию требуется forward-итератору. Такой
        // итератор ни на что не указывает, и разыменовывать его нельзя —
        // ровно как `T*` без инициализации.
        Iterator() = default;

        Iterator(const RingBuffer* owner, std::size_t offset)
            : owner_(owner), offset_(offset) {}

        const T& operator*() const { return owner_->At(offset_); }

        Iterator& operator++() {
            ++offset_;
            return *this;
        }

        // Постфиксная форма тоже нужна: алгоритмы вправе писать `it++`.
        Iterator operator++(int) {
            Iterator before = *this;
            ++offset_;
            return before;
        }

        bool operator==(const Iterator& other) const {
            return offset_ == other.offset_;
        }

        bool operator!=(const Iterator& other) const {
            return offset_ != other.offset_;
        }

     private:
        const RingBuffer* owner_ = nullptr;
        std::size_t offset_ = 0;
    };

    // Дописывает элемент. Если буфер полон, самый старый затирается —
    // окно, а не архив. Возвращать что-либо незачем: вытеснение здесь
    // не событие, а способ работы.
    void PushBack(const T& value) {
        storage_[(begin_ + size_) % N] = value;
        Advance();
    }

    // ЗАНЯТИЕ 3.3. Вторая перегрузка: элемент не копируется, а перемещается.
    //
    // Ради одной строки различия — `std::move(value)` вместо `value` —
    // приходится писать всю функцию заново. Так и есть, и это не изъян
    // кольцевого буфера: ровно так же устроен любой контейнер стандартной
    // библиотеки, у vector те же две перегрузки push_back. Устранить это
    // дублирование можно только идеальной передачей, а её курс
    // не проходит.
    //
    // Обратите внимание: внутри стоит std::move(value), хотя value — уже
    // rvalue-ссылка. Без него не сработает: сама ссылка — lvalue, и
    // присваивание выбрало бы копирующую форму. Это самая частая ошибка
    // в первом коде на move-семантике, и компилятор о ней молчит.
    void PushBack(T&& value) {
        storage_[(begin_ + size_) % N] = std::move(value);
        Advance();
    }

    void Clear() {
        begin_ = 0;
        size_ = 0;
    }

    std::size_t size() const { return size_; }
    static constexpr std::size_t capacity() { return N; }
    bool empty() const { return size_ == 0; }
    bool full() const { return size_ == N; }

    // По логическому индексу: 0 — самый старый.
    const T& operator[](std::size_t index) const { return At(index); }

    // Самый новый элемент. Вызывать на пустом буфере нельзя — это ошибка
    // в коде вызывающего, а не случай, который надо обрабатывать.
    const T& back() const { return At(size_ - 1); }

    Iterator begin() const { return Iterator(this, 0); }
    Iterator end() const { return Iterator(this, size_); }

 private:
    // Сдвиг границ после записи. Вынесено потому, что двух перегрузок
    // PushBack стало две, а логика вытеснения у них одна.
    void Advance() {
        if (size_ < N) {
            ++size_;
        } else {
            // Буфер полон: начало сдвигается, самый старый элемент только что
            // перезаписан. Ни освобождения, ни сдвига содержимого.
            begin_ = (begin_ + 1) % N;
        }
    }

    const T& At(std::size_t offset) const {
        return storage_[(begin_ + offset) % N];
    }

    std::array<T, N> storage_{};
    std::size_t begin_ = 0;
    std::size_t size_ = 0;
};

}  // namespace nano_edr

#endif  // NANO_EDR_KIT_RING_BUFFER_H
