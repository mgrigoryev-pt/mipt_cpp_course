// RAII-обёртка над границей os.h. Занятие 2.1.
//
// Это центральный артефакт занятия, и почти всё в нём — следствие одного
// вопроса: как класс сообщает, что не смог создаться.
//
// У конструктора нет канала для кода возврата. Значит исход ровно один
// из двух: корректный объект или исключение. Никакого is_valid(), никакого
// «объект создан, но пользоваться нельзя»: такой объект приходится проверять
// после каждого создания, и однажды проверку забудут.
//
// Деструктор, наоборот, не бросает никогда. Он зовёт os_free — а тот, по
// контракту границы, не бросает и не возвращает кода. Если бы возвращал,
// деструктор всё равно не смог бы ничего с этим сделать: бросать из деструктора
// нельзя, потому что он вызывается при раскрутке стека, и второе исключение
// в этот момент завершает программу.
//
// Копирование запрещено, и это не осторожность. os_handle* — владеющий
// ресурс, за которым стоит открытый файл, поток и отчёт; две обёртки над одним
// указателем позвали бы os_free дважды. Запретить копирование дешевле, чем
// придумывать, что оно должно значить.
//
// Каналы отказа распределены так:
//
//   конструктор  -> исключение          не создался — работать нечем
//   Subscribe    -> исключение          нарушение порядка вызовов, ошибка кода
//   Start        -> исключение          то же
//   Wait         -> os_status           OS_TIMEOUT — штатный исход, не отказ
//   Stop         -> ничего              звать можно всегда, в том числе дважды
//
// Wait возвращает код именно потому, что OS_TIMEOUT — не ошибка, а тик агента:
// на нём выполняется вытеснение старых записей и печать статистики. Функция,
// которая бросала бы на штатном исходе, была бы непригодна.
//
// ЧТО ДОБАВИЛО ЗАНЯТИЕ 3.3: ДЕЙСТВИЯ
//
// До этого занятия обёртка умела только слушать. Теперь она умеет вмешиваться:
// убить процесс, перенести файл, удалить файл, спросить систему про процесс.
//
// Все четыре возвращают os_status, и ни одна не бросает. Это не отступление
// от линии «конструктор бросает, потому что другого канала нет», а её
// продолжение: канал выбирается по природе отказа, а не по вкусу.
//
//   os_init не смог          работать нечем, дальше идти некуда   исключение
//   подписка не по порядку   ошибка в коде, а не в данных         исключение
//   процесс уже умер         ШТАТНЫЙ исход реагирования           код
//   файл занят другим        то же                                код
//   pid переиспользован      то же, и обработка у него своя       код
//
// Между сработкой и реагированием проходит время. Процесс, на который
// сработало правило, к моменту действия мог завершиться сам — и это не
// исключительная ситуация, а обычный ход событий на живой машине. Больше
// того: у каждого кода отказа своя реакция. OS_NO_SUCH_PROCESS означает
// «поздно, но не страшно»; OS_PID_REUSED означает «стой, это уже не он»;
// OS_ACCESS_DENIED означает «доложить наверх, сами мы не справимся».
// Исключение здесь смешало бы три разных исхода в один catch.

#ifndef NANO_EDR_KIT_OS_HANDLE_H
#define NANO_EDR_KIT_OS_HANDLE_H

#include <cstdint>
#include <string>

#include "os.h"

namespace nano_edr {

class OsHandle {
 public:
    // Зовёт os_init. Бросает std::runtime_error, если тот не вернул OS_OK:
    // в сообщении — путь и os_status_str, потому что «не удалось
    // инициализировать» без причины бесполезно.
    explicit OsHandle(const std::string& config_path);

    // Зовёт os_free: тот сам останавливает поток и пишет отчёт. Не бросает.
    ~OsHandle();

    OsHandle(const OsHandle&) = delete;
    OsHandle& operator=(const OsHandle&) = delete;

    // Подписка на поток событий. Подписчик один, отписки нет — так устроена
    // граница. Бросает std::runtime_error при отказе.
    //
    // callback обязан быть noexcept и обязан не выпускать исключения наружу:
    // раскрутка стека через кадры C — неопределённое поведение. Отсюда приём
    // «статический метод-трамплин»: C-API принимает указатель на функцию
    // и void*, трамплин достаёт из контекста объект и зовёт его метод, поймав
    // внутри всё.
    void Subscribe(os_event_cb callback, void* context);

    // Запуск доставки. Бросает std::runtime_error при отказе.
    void Start();

    // Ожидание событий. Возвращает код: OS_TIMEOUT означает «истёк бюджет
    // модельного времени, событий пока нет» — это тик агента, а не ошибка.
    // OS_OK означает, что поток кончился.
    os_status Wait(uint32_t timeout_ms);

    // Остановка доставки. Звать можно всегда, в том числе повторно и после
    // конца потока. Не бросает.
    void Stop();

    // --- действия. Занятие 3.3 ------------------------------------------

    // Завершить процесс. expected_start_time — время старта того процесса,
    // который вы собирались убить: если номер уже достался другому, граница
    // вернёт OS_PID_REUSED и никого не тронет.
    //
    // Ноль в expected_start_time означает «не проверять». Так писать можно,
    // и симулятор считает такие вызовы отдельной строкой отчёта — потому что
    // это способ однажды убить невиновный процесс. Обёртка ноль не запрещает:
    // запрещать его должен тот, кто вызывает, и по причине, которую понимает.
    os_status Kill(uint32_t pid, uint64_t expected_start_time);

    // Перенести файл. Путь назначения существующий файл заменяет, как rename;
    // каталоги не проверяются, путь — просто строка.
    os_status MoveFile(const std::string& from, const std::string& to);

    // Удалить файл.
    os_status DeleteFile(const std::string& path);

    // --- состояние. Занятие 3.3 -----------------------------------------

    // Спросить систему про живой процесс. Дорого и гоночно: между ответом
    // и следующей строкой кода процесс может умереть. Каждый такой вызов
    // считается в отчёте, и у сценария на них есть бюджет — потому что агент,
    // опрашивающий систему на каждое событие, на живой машине неприемлем.
    //
    // Возвращает OS_NO_SUCH_PROCESS про всё, чего уже нет: истории у системы
    // нет, только текущее состояние.
    os_status ProcessInfo(uint32_t pid, os_process_info* out);

 private:
    os_handle* handle_ = nullptr;
};

}  // namespace nano_edr

#endif  // NANO_EDR_KIT_OS_HANDLE_H
