// Источник событий как интерфейс. Занятие 2.3.
//
// На занятии 2.1 источников стало два — файл и граница os.h, — и выбирал между
// ними `if` в main. Дублирование было видно нарочно: интерфейса ещё не было.
// Теперь он есть, и `if` остаётся ровно один — тот, что создаёт нужный
// источник. Всё остальное работает с IEventSource и про файлы с границами
// не знает.
//
// Обратное направление тоже через интерфейс. Источник не знает, кому отдаёт
// события: у него есть IEventHandler, и всё. Иначе интерфейс источника
// пришлось бы объявлять поверх конкретного класса агента, а это ровно та
// зависимость, от которой интерфейс и должен избавлять.
//
// Отсюда буквальный смысл фразы «агент не знает, откуда события, а источник
// не знает, кому их отдаёт». Проверяется это просто: те же эталоны прогоняются
// через оба источника.

#ifndef NANO_EDR_KIT_EVENT_SOURCE_H
#define NANO_EDR_KIT_EVENT_SOURCE_H

#include "event.h"

namespace nano_edr {

// Кому источник отдаёт события.
class IEventHandler {
 public:
    virtual ~IEventHandler() = default;

    // Событие разобрано и корректно.
    virtual void HandleEvent(const Event& event) = 0;

    // Строку можно пропустить молча: пустая или комментарий.
    virtual void OnSkipped() = 0;

    // Строку разобрать не удалось. Это не то же самое, что пропустить:
    // комментарий — не проблема журнала, а битая строка — проблема.
    virtual void OnBroken() = 0;

    // Событий пока нет, время идёт. Здесь агент делает периодическую работу.
    virtual void OnTick() = 0;
};

// Откуда берутся события.
class IEventSource {
 public:
    virtual ~IEventSource() = default;

    // Работает до конца потока. Бросает std::runtime_error, если источник
    // отказал по-настоящему; конец потока отказом не считается.
    virtual void Run(IEventHandler* handler) = 0;
};

}  // namespace nano_edr

#endif  // NANO_EDR_KIT_EVENT_SOURCE_H
