// Окно последних событий. Занятие 2.1.
//
// Список тот же, что на 1.2, но у него появился инвариант, и держит его теперь
// сам тип: size равен числу узлов, tail указывает на последний, вместимость
// не превышается. На 1.2 за этим следил вызывающий, то есть никто — и тесты
// специально считали узлы отдельно, чтобы поймать расхождение.
//
// Отсюда всё остальное: поля стали приватными, свободные функции — методами,
// а деструктор остался ровно таким же обязательным. Владеет узлами список,
// и вернуть их некому, кроме него.
//
// Копирование запрещено, и это правило трёх из лекции 5 в чистом виде.
// У списка есть деструктор, который удаляет узлы, — значит сгенерированное
// компилятором копирование неверно по построению: копия получит те же адреса,
// и каждый узел удалится дважды. Выбор из двух — написать копирование самому
// или запретить, — и здесь правильнее запретить: окно событий одно на агента,
// а молча скопировать тысячу узлов никто не хотел. Перемещение появится
// на занятии 3.3, где будет с чем сравнивать.

#ifndef NANO_EDR_KIT_EVENT_LIST_H
#define NANO_EDR_KIT_EVENT_LIST_H

#include <cstddef>

#include "event.h"

namespace nano_edr {

// Узел не владеет ничем: next — указатель на следующий узел, а сами узлы
// принадлежат списку.
//
// Конструктор нужен потому, что Event больше не создать «пустым»: у него
// инвариант. Это первое место, где инвариант одного типа заставляет
// поменяться другой, — и стоит заметить, что заставил он в правильную сторону.
struct EventNode {
    explicit EventNode(const Event& value) : event(value) {}

    Event event;
    EventNode* next = nullptr;
};

class EventList {
 public:
    // Вместимость: 0 означает «без ограничения». Так один и тот же список
    // годится и как окно, и как хранилище.
    explicit EventList(std::size_t capacity = 0) : capacity_(capacity) {}

    ~EventList();

    EventList(const EventList&) = delete;
    EventList& operator=(const EventList&) = delete;

    // Дописывает копию события в конец. Если вместимость задана и список
    // полон, самое старое событие уходит: окно, а не архив. После вызова
    // size() <= capacity() всегда.
    void PushBack(const Event& event);

    // Убирает самое старое. На пустом списке ничего не делает и ошибкой
    // не считается: «убрать из пустого» — обычный ход событий.
    void PopFront();

    void Clear();

    std::size_t size() const { return size_; }
    std::size_t capacity() const { return capacity_; }
    bool empty() const { return size_ == 0; }

    // Голова цепочки для обхода. Указатель на чужой узел: владеет им список,
    // а вызывающий только смотрит. nullptr на пустом списке. Итераторы —
    // лекция 13; до тех пор обход руками.
    const EventNode* head() const { return head_; }

    // Последнее добавленное событие или nullptr. Список односвязный, назад
    // по нему не пройти, поэтому хвост хранится отдельно — иначе за ним
    // пришлось бы каждый раз идти от головы.
    const EventNode* back() const { return tail_; }

 private:
    EventNode* head_ = nullptr;
    EventNode* tail_ = nullptr;
    std::size_t size_ = 0;
    std::size_t capacity_ = 0;
};

}  // namespace nano_edr

#endif  // NANO_EDR_KIT_EVENT_LIST_H
