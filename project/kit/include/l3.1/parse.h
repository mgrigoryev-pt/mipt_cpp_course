// Разбор строки журнала. Занятие 2.1.
//
// Формат не изменился: пары `ключ=значение`, разделённые пробелами, значение
// с пробелами в двойных кавычках, экранирования нет.
//
//   ts=1730000001000 type=file_write pid=1042 path="C:\a b.js" size=812
//
// Изменились две вещи.
//
// Первое: разбор больше не возвращает Event. У Event есть инвариант, а разбор
// законно не удаётся — журнал пишет чужой код. Собрать объект с инвариантом
// из обрывка нельзя, поэтому ParseEventLine уступает место ParseEventParts:
// разбор отдаёт EventParts, а Event строится из них уже целиком, и его
// конструктор проверяет то, что обещает.
//
// Второе: вход теперь по const-ссылке. На занятиях 1.2 и 1.3 здесь стоял
// указатель — ссылок ещё не было, а потом менять сигнатуру было слишком дорого:
// сломались бы выданные тесты. Сейчас переписывается всё равно всё, и цена
// стала нулевой. Это и есть ответ на вопрос «когда менять сигнатуру»: не когда
// хочется, а когда за это никто не платит.

#ifndef NANO_EDR_KIT_PARSE_H
#define NANO_EDR_KIT_PARSE_H

#include <string>

#include "event.h"

namespace nano_edr {

// Разбирает строку журнала в части события: первые ts, type и pid — в шапку,
// всё остальное, включая повторы этих ключей, — в fields, в порядке строки.
//
// false, если строка испорчена (незакрытая кавычка, пустой ключ, слово
// без '='), либо это комментарий или пустая строка. Тогда *out использовать
// нельзя: часть пар в нём уже может лежать. Отличить пропускаемую строку
// от испорченной можно через IsBlankOrComment — и нужно: считать их одним
// счётчиком значит прятать проблему журнала за комментарием.
//
// Обратите внимание: событие здесь не проверяется. Есть ли ts и type и число
// ли ts — инвариант Event, и проверяет его конструктор Event, а не разбор.
// Строка без ts разбирается успешно, с пустым ts в EventParts. Один и тот же
// вопрос не должен проверяться в двух местах: рано или поздно проверки
// разойдутся.
bool ParseEventParts(const std::string& line, EventParts* out);

// Строку можно пропустить молча: пустая, из пробелов, либо начинается
// с символа комментария (# или ;).
bool IsBlankOrComment(const std::string& line);

}  // namespace nano_edr

#endif  // NANO_EDR_KIT_PARSE_H
