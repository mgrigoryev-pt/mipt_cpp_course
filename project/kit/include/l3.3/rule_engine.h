// Движок правил. Занятие 3.2.
//
// Что изменилось. Движок наконец сообщает о детекте сам — но не печатает,
// а отдаёт её получателям, про которых знает только то, что они получатели.
//
// История этого места стоит того, чтобы её проследить: она вся про то, как
// ответственность уходит туда, где ей место.
//
//   1.3   печать внутри CheckRules — развести было нечем;
//   2.2   печать переехала в агента — у движка появился вызывающий;
//   2.3   движок отдаёт список сработавших правил и молчит;
//   3.2   движок отдаёт детект получателям и не знает, кто они.
//
// Ни на одном шаге ничего не переписывалось заново. Каждый следующий приём —
// класс, виртуальная функция, стирание типа — снимал ровно одно ограничение
// предыдущего.
//
// ЗАЧЕМ ДВИЖКУ МОДЕЛЬ СУЩНОСТЕЙ
//
// Детект собирает движок — он единственное место, где известно, что правило
// сработало. Чтобы в детекте была цепочка предков, ему нужен тот, кто эту
// цепочку знает. Отсюда SetModel.
//
// Это не нарушение критерия занятия. Критерий про то, что движок не знает
// про каналы вывода — консоль, файл, сеть. Модель сущностей не канал вывода,
// а часть предметной области, ровно как правила и события.
//
// ЗАЧЕМ ОСТАЛСЯ СПИСОК СРАБОТАВШИХ ПРАВИЛ
//
// Подпись ProcessEvent не изменилась, хотя после появления получателей
// выходной параметр движку не нужен. Оставлен он по двум причинам, и первая
// скучная: на нём стоят тесты, выданные на занятии 2.3, и ломать их ради
// косметики — плохая сделка. Вторая содержательная: спросить «какие правила
// сработали» иногда нужно, не заводя получателя, и тесту это удобнее.

#ifndef NANO_EDR_KIT_RULE_ENGINE_H
#define NANO_EDR_KIT_RULE_ENGINE_H

#include <cstddef>
#include <cstdint>
#include <memory>
#include <vector>

#include "alert_sink.h"
#include "detection.h"
#include "entity_model.h"
#include "event.h"
#include "rule.h"

namespace nano_edr {

class RuleEngine {
 public:
    RuleEngine() = default;

    RuleEngine(const RuleEngine&) = delete;
    RuleEngine& operator=(const RuleEngine&) = delete;

    void AddRule(std::unique_ptr<IRule> rule);

    // Подписать получателя детектов. Их может быть сколько угодно, включая
    // ноль: движок без получателей просто молчит, и тесты занятия 2.3,
    // не знающие про получателей вообще, продолжают работать.
    void Subscribe(AlertSink sink);

    // Модель сущностей для обогащения детекта цепочкой предков. Не владеет;
    // nullptr означает «цепочки не будет». Звать до ProcessEvent.
    void SetModel(const EntityModel* model) { model_ = model; }

    // Прогоняет событие по всем правилам и отдаёт детекты получателям.
    //
    // Возвращает число детектов. Если fired не nullptr, в него дописываются
    // указатели на сработавшие правила — невладеющие, действительные пока
    // жив движок.
    std::size_t ProcessEvent(const Event& event,
                             std::vector<const IRule*>* fired);

    std::size_t size() const { return rules_.size(); }
    std::size_t sink_count() const { return sinks_.size(); }

    const IRule& rule(std::size_t index) const { return *rules_[index]; }

 private:
    // Собрать детект из правила, события и модели.
    //
    // ЗАНЯТИЕ 3.3. Здесь появилась единственная копия события за весь путь
    // от границы до вывода — та, что уходит в улики сработки. Она нужна:
    // событие живёт до возврата из ProcessEvent, а сработка живёт дольше
    // (получатель, подавляющий дубликаты, держит её; планировщик читает её
    // после). Копия осознанная, посчитанная и одна на сработку, а не одна
    // на событие. Разница между этими двумя числами на нагрузочном журнале —
    // четыре порядка.
    Detection MakeDetection(const IRule& rule, const Event& event) const;

    std::vector<std::unique_ptr<IRule>> rules_;
    std::vector<AlertSink> sinks_;
    const EntityModel* model_ = nullptr;
};

}  // namespace nano_edr

#endif  // NANO_EDR_KIT_RULE_ENGINE_H
