// Модель сущностей. Занятие 3.2.
//
// РЕАЛИЗАЦИЯ ВЫДАНА ГОТОВОЙ — `tasks/3.2/handout/entity_model.cpp`, копируется
// в `src/`. Занятие 3.2 про стирание типа, и перебор двух векторов к нему
// отношения не имеет; вашей работой остаётся подключение модели, а с занятия
// 3.3 — и правка самого файла. Подробности — в README рядом с выдачей.
//
// До этого занятия агент помнил только последние события — кольцевой буфер
// на 256 мест. Этого хватает, чтобы ответить «что было секунду назад»,
// и не хватает ни на один вопрос про связи: кто чей родитель, кто записал
// этот файл, откуда взялся этот процесс.
//
// Вопросы эти не выдуманные. Детект без цепочки предков бесполезен: аналитик
// видит «wscript.exe вышел в сеть» и первым делом спрашивает, кто его запустил.
// А реагирование на занятии 3.3 без модели вообще невозможно — убить надо
// поддерево процессов, а не один процесс, и изолировать файл-источник,
// а не тот, который попался в событии.
//
// ЧТО МОДЕЛЬ ЗНАЕТ И ЧЕГО НЕ ЗНАЕТ
//
// Только то, что видела в потоке. Процессы, существовавшие до подписки,
// известны ей ровно настолько, насколько попали в события: pid встретился —
// запись появилась, а image и ppid остались пустыми, потому что их никто
// не сообщал. Поэтому цепочка предков обрывается там, где обрывается знание
// потока, и в выводе это видно: `880>1042(cmd.exe)`.
//
// Спросить у системы (`os_process_info`) модель не пытается, и это выбор,
// а не упущение: у обращений к границе есть бюджет (`max_os_queries`),
// и тратить его на историю — решение занятия 3.3, где появится реагирование
// и обращения к границе станут неизбежны.
//
// ПЕРЕИСПОЛЬЗОВАНИЕ PID
//
// Настоящая проблема, и здесь она решена неправильно — сознательно. Ключ
// записи процесса — pid, и `process_start` с уже известным pid перезаписывает
// запись: старый процесс из модели исчезает вместе со своей цепочкой.
// Правильный ключ — пара `(pid, start_ts)`, но пара как ключ требует
// словаря и специализации `std::hash`, а это занятие 4.1. Сценарий `pid_reuse`
// существует именно затем, чтобы это ограничение было видно, а не описано.
//
// ХРАНИЛИЩЕ
//
// Два вектора и линейный поиск. Словарей ещё нет — они на 4.1, и там же этот
// поиск заменится с замером. На нескольких десятках процессов разницы
// не будет, и увидеть это своими глазами полезнее, чем сразу писать словарь.
//
// А вот на потоке разница будет, и большая: поиск идёт на каждом событии,
// и длина его — число известных сущностей. Сколько именно это стоит —
// вопрос нагрузочного сценария, и ответ на него стоит получить своими руками
// прежде, чем на 4.1 появится словарь. Замер без предварительной догадки
// ничему не учит.

#ifndef NANO_EDR_KIT_ENTITY_MODEL_H
#define NANO_EDR_KIT_ENTITY_MODEL_H

#include <cstddef>
#include <string>
#include <vector>

#include "event.h"

namespace nano_edr {

// Процесс, как его видел поток.
struct ProcessRecord {
    std::string pid;
    std::string ppid;     // пусто, если процесс появился не через process_start
    std::string image;    // пусто по той же причине
    std::string cmdline;
    Timestamp start;
    bool alive = true;
};

// Файл, как его видел поток.
struct FileRecord {
    std::string path;
    std::string creator_pid;  // кто создал: file_create или file_move в этот путь
    std::string writer_pid;   // кто записал последним
    Timestamp last_write;
    bool deleted = false;

    // ЗАНЯТИЕ 3.3. Путь появился переименованием, а не записью.
    //
    // Различие выглядит мелким и стоит сорока файлов данных. Шифровальщик
    // создаёт путь `quarterly.xlsx.locked` — создаёт по-настоящему, этого
    // пути раньше не было, и создатель у него он. Реагирование, которое
    // удаляет всё созданное процессом, удалит документы жертвы.
    //
    // Переименованное — это чьи-то данные под другим именем. Принесённое —
    // это груз атакующего. Удалять можно второе.
    bool from_move = false;
};

class EntityModel {
 public:
    // Пределы хранилища. Модель живёт в агенте, агент — на потоке без конца,
    // и хранилище без предела означает, что агент однажды съест память хоста.
    // Вытеснение по возрасту и объёму на тике — занятие 4.1; здесь предел
    // грубый, но он есть, и это лучше, чем его отсутствие.
    static constexpr std::size_t kMaxProcesses = 4096;
    static constexpr std::size_t kMaxFiles = 8192;

    // Обновить модель событием. Всё, что модель узнаёт, она узнаёт здесь.
    void Observe(const Event& event);

    // --- точечный доступ ---
    // Возвращают nullptr, если такого нет. Особое значение, а не исключение:
    // «модель про это не знает» — штатный исход, а не отказ. Тот же выбор,
    // что у FindField на занятии 1.3, и по той же причине.
    const ProcessRecord* FindProcess(const std::string& pid) const;
    const FileRecord* FindFile(const std::string& path) const;

    // --- запросы по связям ---

    // Цепочка предков: сам процесс, затем родитель, затем его родитель.
    // Обрывается там, где кончается знание модели. Пустой вектор, если про pid
    // ничего не известно.
    std::vector<std::string> GetAncestorChain(const std::string& pid) const;

    // Поддерево процессов: сам процесс и все его потомки. То, что убивает
    // реагирование на занятии 3.3.
    std::vector<std::string> GetProcessTree(const std::string& pid) const;

    // Пути файлов, созданных этим процессом.
    //
    // ЗАНЯТИЕ 3.3. Параметр brought_only отбирает только принесённое: файлы,
    // появившиеся записью, а не переименованием. Умолчание false оставлено
    // ради тестов занятия 3.2, которые эту функцию уже проверяют; всё, что
    // строит план реагирования, передаёт true и обязано передавать true.
    std::vector<std::string> GetFilesCreatedBy(const std::string& pid,
                                               bool brought_only = false) const;

    // Файл, из-за которого процесс появился.
    //
    // Связка `path_in_cmdline`: среди известных модели файлов ищется тот,
    // чей путь встречается в командной строке процесса. Именно так виден
    // дроппер: `cmd.exe` пишет `%TEMP%\a.js`, затем запускается
    // `wscript.exe C:\...\Temp\a.js`, и связь между двумя событиями — путь.
    //
    // Возвращает nullptr, если связь не нашлась. Так и должно быть в
    // большинстве случаев: у обычного процесса в командной строке нет файла,
    // который кто-то только что записал.
    const FileRecord* FindSpawnSource(const std::string& pid) const;

    // Цепочка предков строкой для вывода и для детекта:
    // `880>1042(cmd.exe)>1101(wscript.exe)`, старший первым. Пусто, если
    // про процесс ничего не известно.
    std::string DescribeChain(const std::string& pid) const;

    std::size_t process_count() const { return processes_.size(); }
    std::size_t file_count() const { return files_.size(); }

 private:
    ProcessRecord* MutableProcess(const std::string& pid);
    FileRecord* MutableFile(const std::string& path);

    // created — путь появился этим событием; from_move — появился
    // переименованием. Второе имеет смысл только вместе с первым.
    void NoteFileWrite(const Event& event, const std::string& path,
                       bool created, bool from_move = false);

    std::vector<ProcessRecord> processes_;
    std::vector<FileRecord> files_;
};

}  // namespace nano_edr

#endif  // NANO_EDR_KIT_ENTITY_MODEL_H
