// Слой доступа к полям события. Занятие 2.1.
//
// Распределение отказов не изменилось с занятия 1.3, и меняться ему незачем:
//
//   поля нет в событии          -> nullptr. Ожидаемый исход, а не поломка.
//   нет обязательного поля      -> исключение. Нарушен контракт формата.
//   значение не разбирается     -> false или подстановка. Битые внешние данные.
//
// Изменилось одно, и это решение стоит объяснить, потому что оно **обратное**
// принятому на занятии 1.3.
//
// Тогда FindField искал только среди fields: ts, type и pid лежали в шапке
// и были доступны напрямую, а три захардкоженных ключа внутри поиска
// выглядели спрятанным правилом. Аргумент был верный — для того кода.
//
// Теперь появились условия-функторы (conditions.h), и им нужно спрашивать
// «тип события равен process_start» так же, как «поле path кончается на .js».
// Если шапка не видна через FindField, особый случай для трёх ключей придётся
// написать в каждом из четырёх условий, а потом и в каждом новом. Одно
// спрятанное правило в одной функции лучше четырёх явных в четырёх.
//
// Это не «раньше решили неправильно». Это решение, у которого поменялись
// входные данные: появился второй потребитель с другими требованиями.
// Так и выглядит нормальная жизнь интерфейса, и на паре стоит сказать об этом
// прямо — иначе студент решит, что верное решение принимается один раз.

#ifndef NANO_EDR_KIT_FIELDS_H
#define NANO_EDR_KIT_FIELDS_H

#include <cstdint>
#include <string>

#include "event.h"

namespace nano_edr {

// ---------------------------------------------------------------------------
// Доступ к полям
// ---------------------------------------------------------------------------

// Значение поля или nullptr, если поля нет.
//
// Ищет и в шапке события — ключи "ts", "type", "pid", — и среди fields.
// При повторяющихся ключах даёт первое вхождение.
//
// Возвращается указатель, а не копия: копировать строку только чтобы
// посмотреть на неё — расточительство, а событий будет два миллиона.
// Указатель действителен столько же, сколько само событие.
const std::string* FindField(const Event& event, const std::string& key);

// Значение обязательного поля.
//
// Бросает std::invalid_argument, если поля нет: раз оно объявлено обязательным,
// его отсутствие — нарушение контракта формата, и вернуть пустую строку значило
// бы соврать вызывающему.
const std::string& GetRequiredField(const Event& event, const std::string& key);

// Целое из поля. false, если поля нет или оно не разбирается как целое.
bool GetIntField(const Event& event, const std::string& key, uint64_t* out);

// Перегрузка со значением по умолчанию — для полей, отсутствие которых
// осмысленно: у события без ppid родителя просто нет.
uint64_t GetIntField(const Event& event, const std::string& key, uint64_t fallback);

// ---------------------------------------------------------------------------
// Предикаты
// ---------------------------------------------------------------------------

bool IsProcessStart(const Event& event);
bool IsFileWrite(const Event& event);
bool IsNetConnect(const Event& event);

// Путь из поля path заканчивается на suffix. Без учёта регистра.
bool PathEndsWith(const Event& event, const std::string& suffix);

// Подстрока в командной строке. Тоже без учёта регистра.
bool CommandLineContains(const Event& event, const std::string& needle);

// Приведение пути к сравнимому виду: регистр, разделители, раскрытие %TEMP%.
// Возвращает новую строку; событие не меняется.
//
// Нормализация заведомо неполная — символические ссылки, короткие имена вида
// PROGRA~1, точки внутри пути остаются. Так и должно быть: полная нормализация
// путей — задача не на одно занятие, и делать вид, что решили, вреднее,
// чем признать границы.
std::string NormalizePath(const std::string& path);

}  // namespace nano_edr

#endif  // NANO_EDR_KIT_FIELDS_H
