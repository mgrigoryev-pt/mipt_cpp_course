// Таблица правил на указателях на функции.
//
// Это уже настоящий движок правил — просто самый примитивный из возможных.
// Правило здесь есть идентификатор, важность и функция-проверка; агент гоняет
// каждое событие по таблице и печатает сработки. Ни виртуальных функций,
// ни шаблонов, ни состояния: всё это появится на занятиях 2.2, 2.3 и 3.1,
// и тогда будет с чем сравнивать.
//
// Ограничение этой формы видно сразу, и разговор о нём — часть занятия:
// правило-функция не может ничего помнить. «Двадцать файлов за десять секунд»
// и «wscript, запущенный из winword» так не выражаются — им нужно состояние.
// На занятии 3.1 таблица уступит место правилам с окном событий.

#ifndef NANO_EDR_KIT_RULES_H
#define NANO_EDR_KIT_RULES_H

#include "event.h"

namespace nano_edr {

// Важность сработки. enum class, а не обычный enum: с обычным `kLow` утёк бы
// в окружающую область имён, а сравнение с целым компилировалось бы молча.
enum class Severity { kLow, kMedium, kHigh, kCritical };

// Строковое имя важности для печати. Возвращает "?" на значении вне
// перечисления — такое приходит только из битого приведения, но падать из-за
// него не за что.
const char* SeverityName(Severity severity);

// Проверка правила: одно событие на входе, «сработало или нет» на выходе.
//
// Указатель на функцию, а не std::function: нужен тип, который можно положить
// в constexpr-таблицу, и никакого захвата состояния здесь всё равно нет.
using RuleFn = bool (*)(const Event& event);

struct Rule {
    const char* id;        // короткое имя, которое попадёт в вывод и в отчёт
    RuleFn      check;
    Severity    severity;
};

// Прогоняет событие по таблице и печатает сработавшие правила.
//
// Возвращает число сработок. Таблица передаётся указателем и длиной, а не
// контейнером: контейнеры начинаются с лекции 13, а массив с длиной — то, что
// C++ умел с самого начала, и то, во что превращается любой контейнер на
// границе с C.
size_t CheckRules(const Event& event, const Rule* rules, size_t rule_count);

}  // namespace nano_edr

#endif  // NANO_EDR_KIT_RULES_H
