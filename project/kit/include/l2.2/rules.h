// Важность детекта. Занятие 2.2.
//
// От заголовка занятия 1.3 здесь остались две сущности из пяти. Таблица
// указателей на функции — `RuleFn`, `Rule`, `CheckRules` — ушла, и её место
// заняли классы правил в rule.h.
//
// Ушла она не потому, что «классы лучше». Правило-функция не может ничего
// хранить: ни идентификатора, ни важности, ни счётчика срабатываний, ни списка
// действий. Всё это приходилось держать рядом с указателем, в структуре Rule,
// то есть отдельно от логики. Как только у правила появляется состояние,
// таблица перестаёт быть таблицей.

#ifndef NANO_EDR_KIT_RULES_H
#define NANO_EDR_KIT_RULES_H

namespace nano_edr {

// Важность детекта. enum class, а не обычный enum: с обычным `kLow` утёк бы
// в окружающую область имён, а сравнение с целым компилировалось бы молча.
enum class Severity { kLow, kMedium, kHigh, kCritical };

// Строковое имя важности для печати. Возвращает "?" на значении вне
// перечисления — такое приходит только из битого приведения, но падать
// из-за него не за что.
const char* SeverityName(Severity severity);

}  // namespace nano_edr

#endif  // NANO_EDR_KIT_RULES_H
