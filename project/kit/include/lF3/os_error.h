// Отказ границы os.h как плюсовой тип. Занятие Ф2.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ ТИП, ЕСЛИ ЕСТЬ os_status
//
// Затем, что os_status — часть языка C и часть чужого заголовка. Пока он
// возвращается из обёртки наружу, весь агент знает про границу: сравнивает
// с OS_OK, зовёт os_status_str, подключает os.h ради одного перечисления.
// Стоит под границей оказаться живой системе — кодов станет больше,
// и править придётся не обёртку, а всех, кто её звал.
//
// Правило простое, и критерий занятия сформулирован ровно им: **ни один
// os_status не виден выше обёртки.** Поднимается не код, а решение о том,
// что этот код значит.
//
// ТРИ ПОЛЯ, И КАЖДОЕ ДЛЯ СВОЕГО ЧИТАТЕЛЯ
//
//   kind      для кода. По нему ветвится реагирование, и только по нему;
//   text      для человека. Ровно то, что печатала граница, — чтобы
//             диагностика не расходилась с отчётом симулятора;
//   context   что именно делали. «OS_BUSY» без «удаляли C:\...\a.js»
//             отправляет читателя искать место вызова руками.
//
// Почему kind, а не тот же os_status в другой обёртке: перечисление обёртки
// закрыто по смыслу, а не по реализации. OS_TIMEOUT и OS_STOPPED сюда
// не попадают вообще — это не отказы, а исходы ожидания, и им место
// в WaitOutcome. Тип, в который нельзя положить «успех», — это тип, который
// невозможно проверить не тем сравнением.
//
// text — const char*, и это не небрежность: os_status_str возвращает строковый
// литерал со статическим временем жизни. Копировать его в std::string значило
// бы аллоцировать на каждый отказ ради строки, которая переживёт программу.

#ifndef NANO_EDR_KIT_OS_ERROR_H
#define NANO_EDR_KIT_OS_ERROR_H

#include <expected>
#include <string>

#include "os.h"

namespace nano_edr {

// Вид отказа. Закрытое множество: то, на что вызывающий имеет право
// реагировать по-разному.
enum class OsErrorKind {
    kNoSuchProcess,   // нет такого pid, или процесс уже завершён
    kNoSuchFile,
    kPidReused,       // pid жив, но это уже другой процесс
    kAccessDenied,    // процесс защищён
    kBusy,            // файл занят
    kInvalidArg,      // пустой путь, слишком длинный путь, NULL
    kBadCall,         // порядок вызовов нарушен: ошибка кода, а не данных
    kConfigError,     // сценарий не читается или противоречив
    kIoError,
    kUnsupported,     // бэкенд не умеет: скелет os_real
    kUnknown,         // код, которого этот код не знает. Не падать же
};

// Отказ границы.
struct OsError {
    OsErrorKind kind = OsErrorKind::kUnknown;
    const char* text = "";
    std::string context;

    // «os_file_delete(C:\a.js): OS_BUSY». Один формат на все места: три места
    // с тремя форматами читаются как три разные проблемы.
    std::string Message() const;
};

// Перевод кода границы в вид отказа. Единственное место в программе, где
// os_status превращается во что-то плюсовое.
//
// OS_OK, OS_TIMEOUT и OS_STOPPED сюда передавать нельзя: это не отказы.
// Вызывающий обязан разобрать их до вызова — и структура кода такова, что
// иначе не получится.
OsErrorKind OsErrorKindOf(os_status status);

// Собрать отказ: вид, строку границы и описание того, что делали.
OsError MakeOsError(os_status status, std::string context);

// Текст исхода действия — для строки журнала: успех или причина отказа.
//
// Функция маленькая до неприличия, и существует она ровно затем, чтобы
// строка «OS_OK» не появилась ни в одном файле выше обёртки. Иначе критерий
// занятия («ни один статус os.h не виден выше обёртки») превращается
// в «почти ни один», а «почти» здесь и есть та щель, через которую граница
// расползается обратно.
//
// Возвращает указатель на статическую строку: у отказа это то же, что
// в OsError::text, у успеха — литерал.
const char* OutcomeText(const std::expected<void, OsError>& result);

}  // namespace nano_edr

#endif  // NANO_EDR_KIT_OS_ERROR_H
