// Разбор строки журнала. Занятия 2.1 и Ф2.
//
// Формат не менялся ни разу с занятия 1.2: пары `ключ=значение`, разделённые
// пробелами, значение с пробелами в двойных кавычках, экранирования нет.
//
//   ts=1730000001000 type=file_write pid=1042 path="C:\a b.js" size=812
//
// ЧТО ИЗМЕНИЛОСЬ НА Ф2
//
// Разбор перестал владеть тем, что разобрал. Раньше он резал строку на куски
// через substr — то есть заводил новую std::string на каждый ключ и на каждое
// значение, а потом ещё одну при укладке пары в вектор. Теперь он возвращает
// std::string_view: пару чисел, указывающих внутрь той же строки, из которой
// разбирали.
//
// ГЛАВНАЯ ЛОВУШКА, И ОНА НЕ ТЕОРЕТИЧЕСКАЯ
//
// string_view не владеет. Всё, что он вернул, действительно ровно столько,
// сколько жив исходный текст, — и ни секундой дольше. Три способа получить
// висящий view, которые компилятор пропустит молча:
//
//   1. разобрать временную строку:  ParseFields(MakeLine(), &out);
//   2. вернуть view на локальную строку из функции;
//   3. в трамплине границы os.h — сохранить view на ev->fields[i].value
//      дальше возврата из колбэка: строки события действительны только
//      на время вызова, так сказано в контракте os.h.
//
// Ни один из трёх не даёт ошибки сборки. Все три даёт ASan. Поэтому прогон
// под санитайзером на этом занятии — не украшение критерия, а сам критерий.
//
// ПОЧЕМУ СТАРЫЕ ПОДПИСИ ОСТАЛИСЬ
//
// Функции, отдающие Field и EventParts, никуда не делись — они стали
// переходниками в три строки поверх смотрящих. Причина утилитарная: на них
// стоят выданные тесты занятий 1.2 и 2.1, и ломать зелёный набор ради того,
// что и так не в горячем пути, не за что. Заодно это ответ на вопрос, который
// обычно задают в этом месте: переход на string_view не обязан быть
// одномоментным, и слой, разбирающий десяток строк конфигурации за прогон,
// вправе остаться на строках.
//
// Перегрузка выбирается по типу выходного параметра, а не по входному: оба
// принимают string_view, и std::string превращается в него сам.

#ifndef NANO_EDR_KIT_PARSE_H
#define NANO_EDR_KIT_PARSE_H

#include <string_view>
#include <vector>

#include "event.h"

namespace nano_edr {

// Разбирает пары `ключ=значение` из текста, не аллоцируя.
//
// true — разобрано, пары ДОПИСАНЫ в *out (вектор не очищается: так его можно
// переиспользовать между строками, и именно так его и надо использовать).
// false — текст испорчен (незакрытая кавычка, пустой ключ, слово без '='),
// и тогда *out использовать нельзя: часть пар в нём уже может лежать.
//
// Пустой текст — успех и ноль пар, а не отказ.
//
// Всё, что лежит в *out, смотрит внутрь text и действительно ровно столько,
// сколько жив text.
bool ParseFields(std::string_view text, std::vector<FieldView>* out);

// Владеющая форма. Переходник поверх предыдущей: строки копируются.
// Оставлена ради выданных тестов 1.2 и 2.1 и ради разбора конфигурации,
// где десяток строк за прогон и экономить не на чем.
bool ParseFields(std::string_view text, std::vector<Field>* out);

// Разбирает строку журнала в части события: ts, type и pid в шапку, остальное
// в fields. Не аллоцирует, если *out переиспользуется между строками:
// вектор внутри очищается, но вместимость сохраняет.
//
// false, если строка испорчена, либо это комментарий или пустая строка, либо
// в ней нет ts или type. Отличить пропускаемую строку от испорченной можно
// через IsBlankOrComment — и нужно: считать их одним счётчиком значит прятать
// проблему журнала за комментарием.
//
// Обратите внимание: здесь только «есть ли ts», без проверки, что это число.
// Число проверяет конструктор Event, потому что это его инвариант, а не дело
// разбора. Один и тот же вопрос не должен проверяться в двух местах: рано или
// поздно проверки разойдутся.
bool ParseEventParts(std::string_view line, EventPartsView* out);

// Владеющая форма — переходник, как и у ParseFields.
bool ParseEventParts(std::string_view line, EventParts* out);

// Строку можно пропустить молча: пустая, из пробелов, либо начинается
// с символа комментария (# или ;).
bool IsBlankOrComment(std::string_view line);

}  // namespace nano_edr

#endif  // NANO_EDR_KIT_PARSE_H
