// Отправка сработок наверх отдельным потоком. Занятие Ф3.
//
// ЗАЧЕМ ЗДЕСЬ ВТОРОЙ ПОТОК, ЕСЛИ НА ВХОДЕ ОН ЗАПРЕЩЁН
//
// На входе рабочий поток запрещён контрактом границы os.h: все её вызовы
// обязаны идти с одного потока — того, что зовёт os_wait. Обещание про
// одновременность дано там только для кода МЕЖДУ вызовами os_wait, а в режиме
// inline колбэк исполняется внутри самого os_wait, и симулятор в этом режиме
// не берёт ни одного замка.
//
// На выходе такого запрета нет: за edr.h стоит другая граница, и трогает её
// ровно один поток — этот.
//
// А повод завести его настоящий. `edr_send` здесь пишет строку в файл
// и возвращается мгновенно; в настоящем агенте на его месте сеть.
// Отправка по сети занимает миллисекунды, и делать её на горячем пути
// обработки событий — значит останавливать разбор телеметрии на время
// ответа сервера. Агент, который перестаёт видеть машину, пока докладывает
// о прошлой атаке, бесполезен ровно тогда, когда нужен.
//
// Поэтому обработка кладёт сработку в очередь и идёт дальше, а поток отчёта
// разбирает очередь и разговаривает с сервером.
//
// ЭТА ОЧЕРЕДЬ НЕ ОГРАНИЧЕНА, И ЭТО НЕ НЕДОСМОТР
//
// Стоит сравнить её с той очередью, которой на входе НЕ появилось. Будь она
// там, её пришлось бы ограничить и при переполнении терять — а здесь всё
// наоборот. Оба ответа следуют из одного вопроса: что течёт через очередь
// и с какой скоростью.
//
//   события    приходят со скоростью машины, миллионами. Ограничивать
//              обязательно; потеря части телеметрии — приемлемая цена
//              за то, чтобы агент не встал. И главное: задержка события
//              означает промах по цели, поэтому очереди там не место вовсе;
//   сработки   приходят единицами за прогон. Задержка доклада безвредна,
//              а потеря означает непойманную атаку — терять нельзя
//              ни при какой нагрузке.
//
// Очередь, в которую кладут десяток элементов за прогон, ограничивать
// не от чего. Ограничение здесь было бы обрядом: код, который никогда
// не выполняется, но выглядит осмотрительным.
//
// ЗДЕСЬ ЖИВЁТ ВСЯ ОСТАЛЬНАЯ МЕХАНИКА ЛЕКЦИИ 15
//
//   std::jthread              останавливается и присоединяется сам,
//                             в деструкторе, в том числе при исключении;
//   std::stop_token           штатное завершение без флага и без «поток
//                             когда-нибудь заметит»;
//   condition_variable_any    ждать умеет и работу, и запрос остановки —
//                             обычная condition_variable про stop_token
//                             не знает, и ждать пришлось бы с таймаутом,
//                             то есть опрашивать.
//
// ПОРЯДОК ОБЪЯВЛЕНИЯ ПОЛЕЙ ЗДЕСЬ ЕСТЬ ПОРЯДОК ЖИЗНИ
//
// jthread объявлен ПОСЛЕДНИМ, и это не вкус. Поля уничтожаются в порядке,
// обратном объявлению: поток останавливается и присоединяется первым,
// и только потом исчезают очередь, мьютекс и переменная условия, которыми
// он пользуется. Объявите поток первым — и получите обращение
// к уничтоженному мьютексу на выходе из программы, изредка и не на своей
// машине.

#ifndef NANO_EDR_KIT_REPORTER_H
#define NANO_EDR_KIT_REPORTER_H

#include <condition_variable>
#include <cstddef>
#include <deque>
#include <mutex>
#include <thread>

#include "alert_sink.h"
#include "detection.h"

namespace nano_edr {

// Что делал поток отчёта.
struct ReportStats {
    std::size_t posted = 0;      // положено сработок
    std::size_t sent = 0;        // отправлено получателю
    std::size_t high_water = 0;  // максимум в очереди
};

// Асинхронный получатель сработок.
//
// Оборачивает любой AlertSink и отдаёт вместо него свой: тот кладёт
// в очередь и возвращается. Обёрнутый получатель зовётся только из потока
// отчёта, поэтому сам он о потоках знать не обязан — и не знает.
class Reporter {
 public:
    // sink переходит во владение и вызывается только из потока отчёта.
    explicit Reporter(AlertSink sink);

    // Останавливает поток и дожидается его. Не бросает.
    ~Reporter();

    Reporter(const Reporter&) = delete;
    Reporter& operator=(const Reporter&) = delete;

    // Получатель для подписки. Кладёт сработку в очередь и возвращается;
    // не блокирует и не отправляет ничего сам.
    //
    // Захватывает this, поэтому Reporter обязан пережить агента. В main
    // это обеспечено порядком объявления, а не обещанием.
    AlertSink Sink();

    // Дождаться отправки всего, что положено, и остановить поток.
    //
    // Звать явно, а не полагаться на деструктор, стоит по одной причине:
    // после этого main зовёт edr_flush, и flush обязан идти ПОСЛЕ последней
    // отправки. Деструктор сделает то же самое, но позже, чем нужно.
    // Повторный вызов безвреден.
    void Stop();

    ReportStats stats() const;

 private:
    // Тело потока. Ждёт работу или остановку; на остановке дорабатывает
    // остаток очереди и выходит — сработка, положенная перед завершением,
    // обязана уехать.
    void Loop(std::stop_token stop);

    AlertSink sink_;

    mutable std::mutex mutex_;
    std::condition_variable_any ready_;
    std::deque<Detection> pending_;
    ReportStats stats_;

    // Последним. См. про порядок уничтожения в заголовке файла.
    std::jthread thread_;
};

}  // namespace nano_edr

#endif  // NANO_EDR_KIT_REPORTER_H
