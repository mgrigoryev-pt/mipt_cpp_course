// Детект как отдельный тип. Занятия 3.2 и 3.3.
//
// До занятия 3.2 сработки не существовало. Движок отдавал агенту список
// сработавших правил, агент печатал строку из правила и события — и это
// работало, пока получатель был один и печатал в консоль.
//
// Получателей стало четыре: консоль, файл, счётчик в тестах и канал наверх
// через edr.h. У них общее только одно — то, что им передают. Значит это
// «одно» пора назвать типом, иначе каждый получатель начнёт заново собирать
// его из правила и события, и форматы разойдутся.
//
// Detection — снимок, а не ссылка на живые данные. Внутри строки, а не
// указатели на правило и событие, и это осознанная плата: получатель может
// отложить детект (тот, что подавляет дубликаты, именно так и делает),
// а событие к тому времени уже уничтожено.
//
// ЧТО ДОБАВИЛО ЗАНЯТИЕ 3.3: УЛИКИ И ПРАВИЛО ПЯТИ
//
// К сработке прибавился список улик — событий, на которых правило сработало.
// Нужен он не для красоты: планировщик реагирования (response.h) работает
// по сработке, и одного pid ему мало. Из улики он берёт время, путь, поля —
// то, чего в строке `[DETECT]` нет и не должно быть.
//
// Список сделан move-only: `std::vector<std::unique_ptr<Event>>`. Три
// причины, и ни одна не про экономию байтов.
//
// Первая: у Event нет конструктора по умолчанию — у него инвариант. Хранить
// его в векторе можно, а вот подставлять «пустое событие» некуда, и указатель
// снимает вопрос целиком.
//
// Вторая: перемещение сработки становится перемещением указателей. Сработка
// с тремя уликами — это три события по десятку строк в каждом; move вектора
// указателей копирует три указателя, move вектора событий переместил бы
// тридцать строк.
//
// Третья, и главная: сработку теперь нельзя скопировать. Копирующий
// конструктор не «дорогой» — его нет, и компилятор не даст его позвать.
// Это ровно то, что нужно: сработка — единичный факт. Скопированная сработка
// означала бы два одинаковых доклада наверх, и лучше, если такой код
// не соберётся, чем если он молча заработает.
//
// Отсюда правило пяти в его настоящем виде — не «написать пять функций»,
// а «сказать про все пять»:
//
//   копирующий конструктор   = delete    сработка единична
//   копирующее присваивание  = delete    то же
//   перемещающий конструктор = default   компилятор сделает это лучше
//   перемещающее присваивание= default   то же
//   деструктор               = default   освобождать вручную нечего
//
// Ни одна из пяти не написана руками, и все пять объявлены. Разница между
// «не подумал» и «подумал и решил» видна в коде — этого от правила пяти
// и добиваются.
//
// Заметьте, что тип при этом перестал быть агрегатом: у него объявлены
// конструкторы. Списочная инициализация `Detection{...}` больше не работает,
// и это единственная плата. Сборкой сработки занимается движок, ему всё
// равно.

#ifndef NANO_EDR_KIT_DETECTION_H
#define NANO_EDR_KIT_DETECTION_H

#include <memory>
#include <string>
#include <vector>

#include "event.h"
#include "rules.h"

namespace nano_edr {

// Улики: события, на которых правило сработало. Владеющие указатели, потому
// что улика должна пережить событие, снятое с потока.
using Evidence = std::vector<std::unique_ptr<Event>>;

// Что нашли.
struct Detection {
    std::string rule;
    Severity severity = Severity::kLow;
    Timestamp ts;
    std::string pid;

    // Цепочка предков процесса-якоря, старший первым, в виде
    // «880>1042(cmd.exe)>1101(wscript.exe)». Пусто, если модель сущностей
    // не подключена или про этот процесс ничего не знает.
    //
    // Строкой, а не вектором записей, по скучной причине: всем четырём
    // получателям нужна именно строка, а собирать её четыре раза глупо.
    std::string chain;

    // Что правило предлагает сделать. Планировщик занятия 3.3 читает этот
    // список и превращает в план; сама детект их только несёт.
    std::vector<std::string> actions;

    // Улики. Пусто — законное состояние: правило могло сработать на том,
    // чего в потоке уже нет.
    Evidence evidence;

    Detection() = default;
    ~Detection() = default;

    Detection(const Detection&) = delete;
    Detection& operator=(const Detection&) = delete;

    // noexcept написан, хотя `= default` вывел бы его сам: у всех полей
    // move не бросает. Написан затем, чтобы при добавлении поля, у которого
    // move бросает, объявление перестало компилироваться — а не тихо
    // потеряло noexcept и вместе с ним перемещение внутри vector.
    Detection(Detection&&) noexcept = default;
    Detection& operator=(Detection&&) noexcept = default;
};

// Строка формата `[DETECT]`. Один формат в одном месте: консольный
// и файловый получатели зовут её оба, и разойтись им нечем.
std::string ToString(const Detection& detection);

// ЗАНЯТИЕ Ф3. Копия сработки без улик.
//
// Сработка не копируется — так решено на 3.2 и решено правильно: улики это
// вектор unique_ptr, и копия сработки означала бы копию каждого события
// в ней. Но на Ф3 сработку понадобилось положить в очередь потока отчёта,
// а очередь по определению владеет тем, что в ней лежит.
//
// Тупик здесь мнимый, и выход из него — не ослабить запрет, а посмотреть,
// ЧТО именно уезжает наверх. Наверх уезжают правило, важность, время, номер
// процесса, цепочка предков и список действий. Улики не уезжают: они нужны
// реагированию здесь, на хосте, а не серверу.
//
// Поэтому копируется ровно то, что уходит на границу, а улики остаются
// у оригинала. Это не «облегчённая копия ради скорости», а честный ответ
// на вопрос, который до Ф3 никто не задавал: что из сработки вообще
// является сообщением.
Detection WithoutEvidence(const Detection& detection);

}  // namespace nano_edr

#endif  // NANO_EDR_KIT_DETECTION_H
