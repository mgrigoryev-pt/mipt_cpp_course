// RAII-обёртка над границей os.h. Занятия 2.1, 3.3 и Ф2.
//
// Это центральный артефакт занятия 2.1, и почти всё в нём — следствие одного
// вопроса: как класс сообщает, что не смог создаться. На Ф2 у этого вопроса
// появляется второй ответ, и заголовок переписывается целиком.
//
// ЧТО БЫЛО ДО Ф2
//
// Конструктор либо давал объект, либо бросал: другого канала у конструктора
// нет. Методы возвращали os_status. Работало, и на своём месте было
// правильно — исключение из конструктора остаётся единственным ответом,
// пока в языке нет result-типа.
//
// ЧТО ИЗМЕНИЛОСЬ И ПОЧЕМУ ЭТО НЕ ОТКАЗ ОТ ПРЕЖНЕГО РЕШЕНИЯ
//
// Прочитан std::expected (лекция 14), и появился второй ответ на тот же
// вопрос. Конструктор уезжает в приватные, рядом встаёт статическая фабрика:
//
//     static std::expected<OsHandle, OsError> Open(const std::string& path);
//
// Тот самый приём, который лекция 4 анонсировала на будущее. Разница
// не в стиле, а в том, кто обязан отреагировать. Исключение можно не ловить,
// и тогда оно улетит вверх — иногда это ровно то, что нужно. expected нельзя
// не посмотреть: обращение к значению без проверки — это либо исключение
// std::bad_expected_access, либо неопределённое поведение на operator*,
// а [[nodiscard]] напомнит о самом факте возврата.
//
// Что выбрать — зависит от того, ожидаем ли отказ. Несуществующий сценарий
// в командной строке ожидаем: пользователь опечатался, и агент обязан сказать
// об этом внятно, а не стеком раскрутки. Поэтому Open, а не конструктор.
//
// ПРАВИЛО ПЯТИ ЗДЕСЬ СТАЛО ПЯТЬЮ, А НЕ НУЛЁМ
//
// До Ф2 у обёртки был деструктор и два удалённых копирования — перемещение
// не требовалось. Теперь требуется: фабрика возвращает объект по значению,
// и без перемещающего конструктора эта строка не соберётся.
//
//   копирование   запрещено   два os_free на один указатель
//   перемещение   есть        указатель переезжает, у источника nullptr
//   деструктор    есть        os_free, и он не бросает
//
// Перемещающий конструктор обязан оставить источник в состоянии, которое
// можно уничтожить, — то есть обнулить handle_. Иначе os_free позовётся
// дважды: один раз у источника, другой у приёмника. Это не теория,
// а типовая ошибка, и ловится она санитайзером на первом же прогоне.
//
// Оба помечены noexcept. Не для красоты: без noexcept у перемещения
// std::vector<OsHandle> при росте копировал бы — а копирование запрещено,
// и код бы просто не собрался. Здесь вектора нет, но привычка стоит нуля.
//
// КАКОЙ КАНАЛ ОТКАЗА ГДЕ, ПОСЛЕ Ф2
//
//   Open          expected   отказ ожидаем: не тот путь, битый сценарий
//   Subscribe     expected   нарушение порядка вызовов
//   Start         expected   то же
//   Wait          expected   значение — WaitOutcome, а не «успех или провал»
//   Stop          ничего     звать можно всегда, отвечать нечем
//   действия      expected   отказ — штатный ход событий на живой машине
//   QueryProcess  expected   значение — снимок, отказ — «нет такого»
//
// Исключений в этом заголовке не осталось ни одного, и это не «expected
// победил». Это следствие того, что все отказы границы ожидаемы: она отвечает
// кодом на всё, включая собственные ошибки. Слой выше — источники событий —
// по-прежнему бросает, и на то есть причина: у IEventSource::Run нет ни одного
// вызывающего, который мог бы отказ осмысленно обработать, а обязанность
// проверять есть. Один механизм на слой; менять его на границе слоёв —
// нормально, внутри слоя — нет.
//
// ЧТО ДОБАВИЛО ЗАНЯТИЕ 3.3: ДЕЙСТВИЯ
//
// До 3.3 обёртка умела только слушать. Теперь она умеет вмешиваться: убить
// процесс, перенести файл, удалить файл, спросить систему про процесс.
//
// У каждого отказа своя реакция, и в этом весь смысл того, что вид отказа
// поднимается наверх типом OsErrorKind, а не сообщением:
//
//   kNoSuchProcess   поздно, но не страшно: успел умереть сам
//   kPidReused       стой, это уже не он. Второй попытки не будет
//   kAccessDenied    доложить наверх, сами не справимся
//   kBusy            файл занят: сначала процесс, потом файлы
//
// Исключение смешало бы четыре разных исхода в один catch, а os_status
// протащил бы границу через весь агент. expected с закрытым перечислением
// не делает ни того, ни другого.

#ifndef NANO_EDR_KIT_OS_HANDLE_H
#define NANO_EDR_KIT_OS_HANDLE_H

#include <cstdint>
#include <expected>
#include <string>

#include "os.h"
#include "os_error.h"

namespace nano_edr {

// Исход ожидания. Не «успех или отказ»: и то и другое — нормальная работа.
//
// Отдельный тип вместо bool по той же причине, по которой Timestamp
// не uint64_t: `if (outcome)` не должно компилироваться, потому что читателю
// неоткуда узнать, что означает true.
enum class WaitOutcome {
    kTimeout,    // истёк бюджет модельного времени. Это тик агента
    kFinished,   // поток событий исчерпан либо остановлен
};

// Снимок живого процесса — плюсовой, со строками, которыми владеет он сам.
//
// os_process_info наверх не поднимается: там массивы char фиксированной
// длины, и всякий, кто его получит, обязан помнить про OS_MAX_PATH. Обёртка
// на то и обёртка, чтобы помнить это за всех — один раз.
struct ProcessInfo {
    uint32_t pid = 0;
    uint32_t ppid = 0;
    std::string image;
    std::string cmdline;
    std::string user;
    uint64_t start_time = 0;
};

class OsHandle {
 public:
    // Открыть границу по пути к сценарию.
    //
    // Отказ ожидаем — путь приходит из командной строки, — поэтому expected,
    // а не исключение. В OsError::context лежит сам путь: «не удалось
    // инициализировать» без него бесполезно.
    [[nodiscard]] static std::expected<OsHandle, OsError> Open(
        const std::string& config_path);

    // Зовёт os_free: тот сам останавливает поток и пишет отчёт. Не бросает —
    // и не мог бы: деструктор вызывается при раскрутке стека, и второе
    // исключение в этот момент завершает программу.
    ~OsHandle();

    OsHandle(const OsHandle&) = delete;
    OsHandle& operator=(const OsHandle&) = delete;

    // Перемещение: указатель переезжает, у источника остаётся nullptr.
    OsHandle(OsHandle&& other) noexcept;
    OsHandle& operator=(OsHandle&& other) noexcept;

    // Подписка на поток событий. Подписчик один, отписки нет — так устроена
    // граница.
    //
    // callback обязан быть noexcept и обязан не выпускать исключения наружу:
    // раскрутка стека через кадры C — неопределённое поведение. Отсюда приём
    // «статический метод-трамплин»: C-API принимает указатель на функцию
    // и void*, трамплин достаёт из контекста объект и зовёт его метод, поймав
    // внутри всё.
    [[nodiscard]] std::expected<void, OsError> Subscribe(os_event_cb callback,
                                                         void* context);

    // Запуск доставки.
    [[nodiscard]] std::expected<void, OsError> Start();

    // Ожидание событий. Значение — исход, а не «получилось»: kTimeout
    // означает тик агента, kFinished — конец потока. Ошибка — всё остальное,
    // то есть настоящая поломка.
    [[nodiscard]] std::expected<WaitOutcome, OsError> Wait(uint32_t timeout_ms);

    // Остановка доставки. Звать можно всегда, в том числе повторно и после
    // конца потока. Не бросает и ничего не возвращает: отвечать вызывающему
    // на «остановлено уже остановленное» нечем.
    void Stop();

    // --- действия. Занятия 3.3 и Ф2 -------------------------------------

    // Завершить процесс. expected_start_time — время старта того процесса,
    // который вы собирались убить: если номер уже достался другому, граница
    // ответит kPidReused и никого не тронет.
    //
    // Ноль в expected_start_time означает «не проверять». Так писать можно,
    // и симулятор считает такие вызовы отдельной строкой отчёта — потому что
    // это способ однажды убить невиновный процесс. Обёртка ноль не запрещает:
    // запрещать его должен тот, кто вызывает, и по причине, которую понимает.
    [[nodiscard]] std::expected<void, OsError> Kill(
        uint32_t pid, uint64_t expected_start_time);

    // Перенести файл. Путь назначения существующий файл заменяет, как rename;
    // каталоги не проверяются, путь — просто строка.
    [[nodiscard]] std::expected<void, OsError> MoveFile(const std::string& from,
                                                        const std::string& to);

    // Удалить файл.
    [[nodiscard]] std::expected<void, OsError> DeleteFile(
        const std::string& path);

    // --- состояние. Занятия 3.3 и Ф2 ------------------------------------

    // Спросить систему про живой процесс. Дорого и гоночно: между ответом
    // и следующей строкой кода процесс может умереть. Каждый такой вызов
    // считается в отчёте, и у сценария на них есть бюджет — потому что агент,
    // опрашивающий систему на каждое событие, на живой машине неприемлем.
    //
    // Про всё, чего уже нет, отвечает kNoSuchProcess: истории у системы нет,
    // только текущее состояние.
    [[nodiscard]] std::expected<ProcessInfo, OsError> QueryProcess(uint32_t pid);

 private:
    // Приватный: создать обёртку можно только через Open, а значит только
    // с уже проверенным хендлом. Состояния «объект есть, пользоваться нельзя»
    // в этом классе не существует.
    explicit OsHandle(os_handle* handle) noexcept : handle_(handle) {}

    os_handle* handle_ = nullptr;
};

}  // namespace nano_edr

#endif  // NANO_EDR_KIT_OS_HANDLE_H
