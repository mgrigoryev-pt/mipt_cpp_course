// Событие: тип с инвариантом, и теперь ещё с ценой.
//
// Что изменилось с занятия 2.1 и почему. До лекции 4 Event был агрегатом:
// открытые поля, никаких обещаний. Следить за тем, что в `ts` лежит время,
// а в `type` непустая строка, приходилось коду вокруг — то есть никому.
// Затем у типа появился инвариант, и держит его сам тип:
//
//   ts и type обязательны и непусты — иначе конструктор бросает;
//   после конструирования Event корректен, и проверять это больше негде.
//
// Отсюда исчезает `is_valid()`. У конструктора нет канала для кода возврата
// (лекция 4), поэтому исход ровно один из двух: корректный объект или
// исключение. Полуживых объектов, которые надо проверять после создания,
// в этом коде не бывает.
//
// EventParts остаётся агрегатом, и это не забытый рудимент. Разбор строки —
// операция, которая законно не удаётся: журнал пишет чужой код. Собирать
// из обрывка объект с инвариантом нельзя, поэтому у разбора свой тип-перевозчик
// без обещаний, а Event строится из него уже целиком.
//
// ЧТО ДОБАВИЛО ЗАНЯТИЕ 3.3
//
// Второй конструктор: `Event(EventParts&&)`. Ровно тот же инвариант, ровно
// та же проверка — и ни одной скопированной строки.
//
// Причина в том, как этот код работает на самом деле. EventParts живёт
// от разбора строки до создания Event и после этого не нужен никому:
// и в трамплине границы, и в файловом источнике он локальная переменная,
// которая тут же умирает. Копировать из умирающего объекта — это и есть
// то самое «лишнее копирование», с которого начинается лекция 11.
//
// Сколько это стоит. У события четыре строки шапки и в среднем три-четыре
// поля, то есть ещё шесть-восемь строк. Одиннадцать-двенадцать std::string
// на событие; каждая длиннее пятнадцати символов — это аллокация. Два
// миллиона событий — двадцать с лишним миллионов аллокаций, которых можно
// не делать вообще.
//
// ПРАВИЛО ПЯТИ ИЛИ НУЛЯ: ЗДЕСЬ НОЛЬ, И ЭТО НЕ ЛЕНЬ
//
// У Event нет ни копирующего, ни перемещающего конструктора, ни присваиваний,
// ни деструктора. Не потому, что «пока не понадобилось», а потому, что
// писать их было бы ошибкой:
//
//   все поля — std::string, std::vector и Timestamp;
//   каждое умеет копироваться, перемещаться и освобождаться само;
//   ресурсов, которыми Event владеет напрямую, у него нет вообще.
//
// Компилятор сгенерирует все пять лучше, чем их напишут руками: он не забудет
// поле, добавленное завтра, и поставит noexcept там, где оно верно. Правило
// пяти — про типы, которые владеют ресурсом сами; правило нуля — про все
// остальные, и остальных большинство.
//
// Проверить это не на глаз, а компилятором, можно так (см. выданные тесты):
//
//   static_assert(std::is_nothrow_move_constructible_v<Event>);
//
// Оно проходит — и это то самое `noexcept` у move, которое обеспечивает
// перемещение вектора вместо копирования при росте. Никто его не писал.
//
// ЧТО ДОБАВИЛО ЗАНЯТИЕ Ф2: ВЗГЛЯД БЕЗ ВЛАДЕНИЯ
//
// Появилась третья форма конструктора — из EventPartsView, то есть из набора
// std::string_view на чужой буфер. Причина в том, как разбирается журнал
// из файла.
//
// Раньше строка проходила такой путь: getline даёт std::string, разбор режет
// её на одиннадцать-двенадцать std::string внутри EventParts, конструктор
// Event забирает их перемещением. Одиннадцать аллокаций на событие — и все
// они на объект, который живёт три строки кода.
//
// Теперь разбор не аллоцирует вообще: FieldView смотрит внутрь той же строки,
// которую вернул getline. Аллокации остаются ровно там, где без них нельзя, —
// в конструкторе Event, потому что Event владеет своими строками и обязан
// пережить буфер.
//
// ГДЕ ЭТО НЕ ПОМОГЛО, И ПОЧЕМУ ТАК И ОСТАЛОСЬ
//
// В трамплине границы os.h ничего не изменилось: там строки приходят готовыми
// из C, PartsFromOsEvent собирает EventParts, и Event забирает их
// перемещением. Заменить это на views значило бы сменить одиннадцать
// перемещений на одиннадцать копий — то есть проиграть.
//
// Правило отсюда простое и стоит того, чтобы его сформулировать: string_view
// выигрывает там, где буфер УЖЕ есть и владеть заново незачем. Там, где
// владение уже собрано и его можно передать, выигрывает move.

#ifndef NANO_EDR_KIT_EVENT_H
#define NANO_EDR_KIT_EVENT_H

#include <compare>
#include <cstdint>
#include <format>
#include <ostream>
#include <string>
#include <string_view>
#include <vector>

namespace nano_edr {

// Пара «ключ — значение» из строки журнала.
struct Field {
    std::string key;
    std::string value;
};

// Взгляд на пару из чужого буфера. Занятие Ф2.
//
// Ничем не владеет: обе строки смотрят внутрь того текста, из которого пару
// разобрали. Пока текст жив — всё честно; пережить его нельзя, и ловит это
// не компилятор, а санитайзер.
struct FieldView {
    std::string_view key;
    std::string_view value;
};

// Модельное время в миллисекундах.
//
// Отдельный тип, а не uint64_t, по одной причине: время и размер файла —
// разные вещи, и складывать их друг с другом не должно компилироваться.
// Сравнения даёт `= default`: их шесть, писать руками нечего, а <=> из лекции 5
// делает это одной строкой.
struct Timestamp {
    uint64_t ms = 0;

    auto operator<=>(const Timestamp&) const = default;
    bool operator==(const Timestamp&) const = default;
};


// Тип события перечислением.
//
// До занятия 2.2 тип был строкой, и правила сравнивали строки. Работало,
// но каждое сравнение — это работа во время выполнения и возможность опечатки,
// которую компилятор не заметит: `"proces_start"` соберётся молча.
//
// enum class, а не обычный enum: с обычным `kFileWrite` утёк бы в окружающую
// область имён, а сравнение с целым компилировалось бы без предупреждения.
//
// kOther существует потому, что так устроена граница: неизвестный тип события
// доставляется как есть и моделью не отбрасывается. Агент, падающий на типе,
// которого не знал его автор, бесполезен — телеметрию расширяют без него.
// Строка при этом сохраняется: по kOther не поймёшь, что именно пришло,
// а по type() поймёшь.
enum class EventType {
    kProcessStart,
    kProcessEnd,
    kFileCreate,
    kFileWrite,
    kFileDelete,
    kFileMove,
    kNetConnect,
    kOther,
};

// Разбор и печать. Неизвестная строка даёт kOther, а не отказ.
EventType EventTypeFromString(std::string_view type);
const char* EventTypeName(EventType type);

// Части события, как их дал разбор строки. Агрегат без обещаний.
struct EventParts {
    std::string ts;
    std::string type;
    std::string pid;
    std::vector<Field> fields;
};

// Части события без владения. Занятие Ф2.
//
// Тот же агрегат, что EventParts, только смотрящий. Вектор здесь есть,
// и это не противоречие: он переиспользуется между строками, поэтому после
// первых десятка событий его вместимость перестаёт расти, и аллокаций
// на событие не остаётся ни одной.
//
// Отсюда правило вызова: передавайте один и тот же EventPartsView в цикле,
// а не заводите новый на каждую строку. Новый на каждую строку — это тот же
// вектор, аллоцируемый заново, и весь выигрыш пропадает.
struct EventPartsView {
    std::string_view ts;
    std::string_view type;
    std::string_view pid;
    std::vector<FieldView> fields;
};

// Событие с инвариантом.
class Event {
 public:
    // Бросает std::invalid_argument, если ts или type пусты, либо ts
    // не разбирается как число. Иначе объект корректен — и остаётся таким,
    // потому что менять его снаружи нечем.
    //
    // Копирующая форма: строки из parts копируются, сам parts остаётся
    // пригодным. Нужна там, где parts переиспользуется, — и таких мест
    // в агенте нет ни одного. Оставлена ради тестов и ради того, чтобы
    // разница между двумя формами была видна рядом.
    explicit Event(const EventParts& parts);

    // Перемещающая форма: строки забираются, parts остаётся в состоянии,
    // о котором известно только одно — его можно уничтожить. Пользоваться
    // им после этого нельзя, и именно поэтому аргумент — rvalue-ссылка:
    // компилятор не даст передать сюда то, что вам ещё пригодится, без
    // явного std::move.
    //
    // Проверка инварианта та же и в том же месте: сначала разобрать и
    // проверить ts, потом забирать. Иначе на битой строке мы бы сначала
    // выпотрошили parts, а потом бросили исключение — и вызывающий остался
    // бы с пустым объектом вместо своих данных.
    explicit Event(EventParts&& parts);

    // Из взгляда на чужой буфер. Занятие Ф2.
    //
    // Копирующая по сути: string_view не владеет, а Event обязан владеть,
    // поэтому каждая строка здесь копируется в свою. Перемещать нечего —
    // нечего забирать.
    //
    // Выигрыш не здесь, а до неё: разбор, отдавший эти views, не аллоцировал
    // ни разу, тогда как разбор через EventParts заводил по строке на каждый
    // ключ и на каждое значение, а потом ещё раз при укладке в вектор.
    // Сколько это стоило на самом деле — вопрос к замеру, а не к оценке
    // на глаз; замер входит в критерий занятия.
    explicit Event(const EventPartsView& parts);

    Timestamp ts() const { return ts_; }
    const std::string& raw_ts() const { return raw_ts_; }

    // Тип и строкой, и перечислением. Перечисление — для правил, строка —
    // для вывода и для типов, которых мы не знаем.
    const std::string& type() const { return type_; }
    EventType event_type() const { return event_type_; }
    const std::string& pid() const { return pid_; }
    const std::vector<Field>& fields() const { return fields_; }

 private:
    // Общая часть двух конструкторов: проверить инвариант и разобрать время.
    // Возвращает разобранный ts; бросает, если строка не годится.
    static Timestamp Validate(std::string_view raw_ts,
                              std::string_view type);

    Timestamp ts_;
    std::string raw_ts_;   // как было в журнале: для вывода и диагностики
    std::string type_;
    EventType event_type_ = EventType::kOther;
    std::string pid_;
    std::vector<Field> fields_;
};

// Печать события. Нужна для `std::print("{}\n", event)` — форматтер ниже
// сводится к ней, чтобы формат был в одном месте.
std::string ToString(const Event& event);

// Вывод в поток — упражнение лекции 5. Возвращает поток, чтобы вызовы
// цеплялись друг за друга. Формат тот же, что у ToString: один формат должен
// быть в одном месте, иначе они разойдутся на первой правке.
std::ostream& operator<<(std::ostream& out, const Event& event);

}  // namespace nano_edr

// Форматтер для std::format и std::print — ВЫДАН ГОТОВЫМ.
//
// Это специализация шаблона, а шаблоны начинаются с лекции 8. Писать её сейчас
// не нужно и не просят: она здесь ровно затем, чтобы печать события через
// std::print работала, как требует критерий занятия. Всё, что от вас нужно, —
// написать ToString.
//
// Заодно видно, зачем классу приватные поля: печать идёт через публичный
// интерфейс, и внутренности можно менять, не трогая ни вывод, ни эту
// специализацию.
template <>
struct std::formatter<nano_edr::Event> : std::formatter<std::string> {
    auto format(const nano_edr::Event& event, std::format_context& ctx) const {
        return std::formatter<std::string>::format(nano_edr::ToString(event), ctx);
    }
};

#endif  // NANO_EDR_KIT_EVENT_H
