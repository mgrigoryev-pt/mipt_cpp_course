// Получатели детектов. Занятие 3.2.
//
// Движок не знает ни про консоль, ни про файлы, ни про edr.h — только
// про получателя детектов. Здесь и определено, что такое получатель.
//
// ПОЧЕМУ НЕ ИНТЕРФЕЙС
//
// Можно было бы сделать, как на занятии 2.3: интерфейс `ISink` с чистой
// виртуальной функцией, наследники и вектор `unique_ptr<ISink>`. Но тогда,
// чтобы стать получателем, тип обязан наследовать этот интерфейс.
//
// Лямбда наследовать не может. А контекст в агенте печатает лямбда
// в одну строку, и объявлять под неё класс незачем.
//
// `AlertSink = std::function<void(const Detection&)>` снимает требование
// наследования: получателем становится всё, что вызывается с Detection.
// Классы ниже — получатели с состоянием, которым класс всё равно нужен;
// в агенте рядом с ними живёт лямбда, и движок не отличает одно от другого.
//
// ЗНАЧЕНИЕ, А НЕ УКАЗАТЕЛЬ
//
// Получатель передаётся и хранится по значению. Поэтому получателей можно
// собирать из получателей: FanOutSink раздаёт детект нескольким
// получателям, DedupSink стоит перед другим получателем. Ни движку, ни самим
// получателям про это знать не нужно.

#ifndef NANO_EDR_KIT_ALERT_SINK_H
#define NANO_EDR_KIT_ALERT_SINK_H

#include <cstddef>
#include <functional>
#include <string>
#include <vector>

#include "detection.h"
#include "file_stream.h"

namespace nano_edr {

// Куда уходит детект. Всё, что об этом знает движок.
using AlertSink = std::function<void(const Detection&)>;

// --- получатель первый: консоль -------------------------------------------

// Печатает в stdout строку ToString(detection) и перевод строки.
class ConsoleSink {
 public:
    void operator()(const Detection& detection) const;
};

// --- получатель второй: файл ----------------------------------------------

// То же, что ConsoleSink, но в файл. Строку оба получателя берут из одного
// ToString(detection): две копии формата разошлись бы на первой правке.
class FileSink {
 public:
    // Бросает std::runtime_error, если файл не открылся. Конструктор,
    // у которого нет способа вернуть код ошибки, — занятие 2.1.
    explicit FileSink(const std::string& path);

    void operator()(const Detection& detection);

 private:
    FileStream out_;
};

// --- получатель третий: счётчик для тестов --------------------------------

// Куда счётчик пишет. Отдельная структура, а не поле получателя, по причине,
// которая на этом занятии всплывает первый раз: получатель хранится ВНУТРИ
// AlertSink по значению, то есть тест отдаёт свою копию и больше её не видит.
// Значит наблюдаемое состояние должно жить снаружи, а получатель — только
// указывать на него. Тот же приём, что у трамплина на границе os.h: контекст
// передаётся указателем, владение остаётся у вызывающего.
struct AlertCounter {
    std::size_t total = 0;
    std::vector<Detection> seen;
};

// Увеличивает counter->total и дописывает детект в counter->seen.
class CountingSink {
 public:
    explicit CountingSink(AlertCounter* counter) : counter_(counter) {}

    void operator()(const Detection& detection) const;

 private:
    AlertCounter* counter_ = nullptr;  // не владеет
};

// --- получатель, раздающий нескольким -------------------------------------

// Один получатель снаружи, несколько внутри: Add дописывает получателя
// в sinks_, operator() вызывает каждого по порядку.
//
// Движок и сам раздаёт детект всем подписанным, так что для простой раздачи
// этот класс не нужен. Нужен он, чтобы поставить один DedupSink перед всеми
// получателями сразу: тогда повтор детекта подавляется и попадает в счётчик
// подавленных один раз, а не по разу на каждого получателя.
class FanOutSink {
 public:
    void Add(AlertSink sink);

    void operator()(const Detection& detection) const;

    std::size_t size() const { return sinks_.size(); }

 private:
    std::vector<AlertSink> sinks_;
};

// --- получатель, подавляющий дубликаты ------------------------------------
//
// Этого получателя вы пишете сами — `src/dedup_sink.h`. Публичный интерфейс
// выдан заготовкой `tasks/3.2/skeleton/dedup_sink.h`, а не здесь: этот файл
// вы правите, а комплект менять нельзя. Устройство внутри решаете вы.
// Каталог `src/` стоит на include-пути раньше комплекта, поэтому выданные
// тесты найдут ваш заголовок.
//
// Что он должен делать: пропускать первый детект пары «правило + процесс»
// и молчать про остальные, пока не истечёт срок. Как именно — таблица
// шага 8 в постановке занятия 3.2; тесты — в
// `tasks/3.2/tests/sink_tests.cpp`.
//
// Задача не косметическая. Сценарий ransomware даёт сорок детектов правила
// `ransom_extension` на один и тот же процесс за шесть секунд — это одна
// атака, и сорок строк про неё мешают увидеть остальные три. Настоящий агент
// схлопывает их в одну.
//
// Потеря при этом настоящая: по одной строке не видно, что зашифровано сорок
// файлов. Поэтому подавленные считаются и попадают в сводку — молча терять
// информацию хуже, чем терять её с отчётом.

}  // namespace nano_edr

#endif  // NANO_EDR_KIT_ALERT_SINK_H
