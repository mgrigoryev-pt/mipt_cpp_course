// Детект как отдельный тип. Занятие 3.2.
//
// До этого занятия детекта не существовало. Движок отдавал агенту список
// сработавших правил, агент печатал строку из правила и события — и это
// работало, пока получатель был один и печатал в консоль.
//
// Получателей стало четыре: консоль, файл, счётчик в тестах и канал наверх
// через edr.h. У них общее только одно — то, что им передают. Значит это
// «одно» пора назвать типом, иначе каждый получатель начнёт заново собирать
// его из правила и события, и форматы разойдутся.
//
// Detection — снимок, а не ссылка на живые данные. Внутри строки, а не
// указатели на правило и событие, и это осознанная плата: получатель может
// отложить детект (тот, что подавляет дубликаты, именно так и делает),
// а событие к тому времени уже уничтожено. Цену этой копии считает
// занятие 3.3 — там же появится move-only список улик.

#ifndef NANO_EDR_KIT_DETECTION_H
#define NANO_EDR_KIT_DETECTION_H

#include <string>
#include <vector>

#include "event.h"
#include "rules.h"

namespace nano_edr {

// Что нашли. Агрегат: инварианта здесь нет, потому что собирает его движок,
// а не чужой разбор строки — Detection с пустым rule взяться неоткуда.
struct Detection {
    std::string rule;
    Severity severity = Severity::kLow;
    Timestamp ts;
    std::string pid;

    // Цепочка предков процесса-якоря, старший первым, в виде
    // «880>1042(cmd.exe)>1101(wscript.exe)». Пусто, если модель сущностей
    // не подключена или про этот процесс ничего не знает.
    //
    // Строкой, а не вектором записей, по скучной причине: всем четырём
    // получателям нужна именно строка, а собирать её четыре раза глупо.
    std::string chain;

    // Что правило предлагает сделать. Исполняет это занятие 3.3; здесь
    // детект их только несёт.
    std::vector<std::string> actions;
};

// Строка формата `[DETECT]`. Один формат в одном месте: консольный
// и файловый получатели зовут её оба, и разойтись им нечем.
std::string ToString(const Detection& detection);

}  // namespace nano_edr

#endif  // NANO_EDR_KIT_DETECTION_H
