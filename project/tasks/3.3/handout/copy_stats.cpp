#include "copy_stats.h"

namespace nano_edr {

CopyStats& copy_stats() {
    // Локальная статическая переменная, а не глобальная: инициализация
    // происходит при первом обращении, а не «когда-то до main». Разница
    // становится важной ровно тогда, когда счётчик трогают из конструктора
    // другого глобального объекта, — и тогда порядок инициализации глобальных
    // переменных между единицами трансляции не определён, а этот — определён.
    static CopyStats stats;
    return stats;
}

void ResetCopyStats() {
    copy_stats() = CopyStats();
}

}  // namespace nano_edr
