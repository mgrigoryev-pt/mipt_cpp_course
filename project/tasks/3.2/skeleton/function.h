#ifndef NANO_EDR_FUNCTION_H
#define NANO_EDR_FUNCTION_H

#include <memory>
#include <utility>

namespace nano_edr {

// Объявлен, но не определён — как `FieldTraits` на занятии 3.1. Определена
// только частичная специализация ниже, и это заставляет писать `Function`
// с подписью в скобках: `Function<void(const Detection&)>`. Написать
// `Function<int>` не получится, и это правильно — такой тип бессмыслен.
template <typename Signature>
class Function;

template <typename R, typename... Args>
class Function<R(Args...)> {
 public:
    Function();

    // Ловит любой вызываемый объект. Шаблонный конструктор, а не конструктор
    // от конкретного типа: типов бесконечно много, и в этом весь смысл.
    template <typename F>
    Function(F callable);                                      // NOLINT

    // `const` здесь про сам Function, а не про то, что внутри.
    R operator()(Args... args) const;

    // Пустой Function вызывать нельзя. Проверять до вызова — дело
    // вызывающего, отсюда явное преобразование к bool.
    explicit operator bool() const;
};

}  // namespace nano_edr

#endif  // NANO_EDR_FUNCTION_H
